<p>En octubre de 2015, además de la asamblea general anual, Centre Terre celebró la primera reunión de preparación de la expedición que se realizará
	en enero y febrero del 2017 a la isla Madre de Dios. Tras este primer encuentro se ha avanzado mucho en varios puntos y ha llegado el momento de
	informar sobre los avances.</p>
<h3>El equipo</h3>
<p>El equipo del lado francés, quedó constituido ya en el mes de noviembre. Lamentablemente hubo que descartar unas diez candidaturas por cuestiones
	de espacio. La elección ha sido difícil y ha habido que respetar numerosos criterios de obligado cumplimiento como, por ejemplo, la motivación, la
	presencia de elementos clave, la complementariedad, las competencias indispensables, el equilibrio entre los participantes franceses y chilenos.</p>
<p>En Chile, en breve iniciaremos el proceso de inscripción en coordinación con las universidades que han mostrado interés en colaborar y en función
	de los perfiles de investigación que hemos definido como prioritarios.</p>
<p>El equipo constituido se ha puesto inmediatamente manos a la obra. Todos deben involucrarse a fondo en la búsqueda de partners, indispensables para
	el equilibrio financiero del proyecto: hay que conseguir 40.000 euros (52 millones de pesos) para cuadrar el presupuesto provisional y, por otro
	lado, encontrar colaboradores técnicos que nos abastezcan del material (con un valor monetario estimado de 45.000 euros, es decir, unos 58 millones
	de pesos). En Chile, también es necesario conseguir apoyos para cubrir todas las necesidades logísticas que implica una expedición de este calibre.</p>
<p>Para todos nosotros, esta fase, que durará hasta la partida el 2 de enero del 2017, es difícil y exigente, pero es una fase ineludible que se verá
	recompensada con creces cuando, ya en terreno, podamos recorrer los grandes lapiaces y explorar la isla hasta sus entrañas con el objetivo de
	descubrir las riquezas que atesora.</p>
