<h3>Edición chilena de La isla de los Glaciares de Mármol</h3>
<p>En 2011 Centre Terre confió a Georges la tarea de narrar en un bello libro nuestros veinte años de exploraciones en la Patagonia chilena. El
	entusiasmo de todo el equipo permitió que se alcanzara la suscripción indispensable para la auto-edición de esta obra. Desde un primer momento, antes
	incluso de que el éxito de la edición francesa estuviera asegurado, surgió la idea de una traducción en Chile.</p>
<p>El objetivo era doble. Por un lado, dar a conocer la espeleología en un país donde no se practica. Por otro, disponer de un medio potente para
	difundir la idea que siempre nos rondó desde el 2000, a saber, conseguir un día que Madre de Dios, un territorio absolutamente único en el mundo,
	entre a formar parte del Patrimonio Mundial de la UNESCO.</p>
<p>El camino ha sido largo, pero el proyecto es ya realidad. A finales del 2015, el Ministerio de Bienes Nacionales firmó con Centre Terre el contrato
	de edición. Natalia se encargó de todo el proceso de negociación con los distintos organismos oficiales involucrados en Chile, así como de la
	traducción de los textos al español. La obra, que en breve saldrá a imprenta gracias a la colaboración del SERNATUR de Magallanes (Servicio Nacional
	de Turismo), cuenta con una presentación firmada por el Ministro de Bienes Nacionales Víctor Osorio Reyes. De este modo, una parte de nuestros sueños
	se ha hecho realidad.</p>
<p>Se inicia así una colaboración efectiva y con proyección de futuro entre el Ministerio de Bienes Nacionales y Centre Terre. Uno de los objetivos
	más cercanos será la candidatura de Madre de Dios a Patrimonio de la Humanidad, un expediente que las autoridades chilenas han asumido como propio y
	con el que, evidentemente, colaboraremos a fondo.</p>
<h3>Los preparativos</h3>
<p>¡Están en marcha en todos los frentes!</p>
<p>Un equipo pilotado por Florian se ha puesto manos a la obra para dejar en perfecto estado todos los motores de nuestra flotilla de Bombard… Tendrán
	que estar en plena forma para cuando los carguemos en el conteiner a mediados de septiembre. Stéphane lidera un grupo que se encarga de crear y
	reunir los documentos cartográficos que necesitaremos en terreno. Richard, por otro lado, coordina la definición de un proyecto científico
	multidisciplinario. Otro equipo trabaja en la cobertura médica y de rescate de la expedición. Otros miembros han facilitado las herramientas
	indispensables para hacer un seguimiento contable del proyecto UP 2017, algo complejo debido a que las partidas que involucra son muy diversas. David
	y Olivier han realizado una revisión completa de nuestra página web. Thomas y Arnauld trabajan duro en un proyecto de crowdfounding… Y todo esto sin
	olvidar las necesidades más específicas tales como los campamentos avanzados, las exploraciones subterráneas, el espeleo-buceo… Varios equipos se
	encargan de cuantificar las necesidades logísticas y organizativas propias de cada área.</p>
<p>Finalmente, tenemos nuestro proyecto escolar, capitaneado por José, miembro de Centre Terre y Consejero Técnico Nacional de la Federación Francesa
	de Espeleología. Dos circunscripciones educativas se han unido ya al proyecto: la de Toulouse y la de Lyon. Actualmente, están en curso negociaciones
	con el Ministerio de Educación francés en París. Pueden consultar el proyecto con más detalle en este enlace.</p>
