<h3>El proyecto de base científica</h3>
<p>Una vez desembarquemos en la ribera norte del seno Barros Luco habrá que levantar una pequeña construcción que tendrá una doble finalidad :</p>
<ul>
	<li>a mediano y largo plazo, servir de base científica que permita acoger a los investigadores que vengan hasta este lugar virgen de toda huella
		humana a desarrollar los estudios científicos que permita su excepcional naturaleza;</li>
	<li>a corto plazo, servir de núcleo vital protegido de los rigores del clima con el objetivo de garantizar la recuperación y el brío de los equipos
		que estarán trabajando en terreno.</li>
</ul>
<p>Se trata, por tanto, de un objetivo esencial que no es posible relegar a la improvisación. Además, la isla fue declarada Bien Nacional Protegido,
	lo que significa que el impacto medioambiental de la construcción debe ser lo más cercano posible a cero. Con este objetivo, el equipo UP 2017 se ha
	dotado de las competencias necesarias. Natalia solicitó la ayuda a dos amigas: Cecilia Vera, arquitecta independiente, y Cristina Ibars, experta en
	marketing, del estudio de arquitectura IWAL Ltda. en Santiago. De parte de Centre Terre les encomendó la tarea de definir las características de la
	base científica en función de un pliego de condiciones precisas y de desarrollar un concepto de montaje rápido y seguro. El proyecto también incluye
	la búsqueda de proveedores de los materiales que aseguren la prefabricación y, luego, el ensamblaje en módulos. Al asumir esta gran responsabilidad,
	la pretensión de Cecilia, Cristina y Natalia no era, evidentemente, hacerse cargo de todo. En colaboración con una profesora, Cecilia propuso este
	atípico proyecto a la Universidad Católica como un curso optativo de profundización en arquitectura. El proyecto encontró una buena acogida en la
	Universidad y es así como un grupo de estudiantes inscritos en “Diseño de arquitectura en zonas geográficas remotas” (título inspirado en nuestro
	proyecto de base científica) han iniciado su trabajo a principios de marzo.</p>
