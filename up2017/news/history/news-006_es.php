<h3>Los objetivos</h3>
<p>Es obvio que con tan solo dos meses de presencia en la isla no lograremos estar en todas partes ni recorrerlo todo, de modo que deben fijarse las
	prioridades partiendo del interés potencial de cada lugar, la distancia de nuestra futura base y la dificultad de acceso estimada. Un equipo dirigido
	por Richard trabaja sin descanso para definir exactamente los objetivos mediante los datos geológicos disponibles y, sobre todo, a partir de un
	conjunto de fotografías aéreas y satelitales de alta definición, que ha habido que conseguir previamente. De hecho, sobre todo en las zonas desnudas,
	se identifican emergencias, sumideros, grandes pozos y accidentes geológicos mayores… En terreno, esta documentación será de inestimable valor para
	preparar las salidas diarias y definir los itinerarios de aproximación.</p>
