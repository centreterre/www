<h3>Les objectifs</h3>
<p>En deux mois de présence sur l’île, nous ne pourrons être partout et tout parcourir, c'est une évidence. Il convient donc de se
	fixer des priorités en tenant compte de l’intérêt potentiel de chaque site, de son éloignement de notre future base et de la difficulté d'accès
	estimée. Sous la direction de Richard, une équipe travaille d'arrache-pied à cette définition précise des objectifs, à partir des données géologiques
	disponibles et surtout d’un ensemble de photographies aériennes et satellitaires haute définition qu’il a fallu rassembler. Émergences, pertes de
	ruisseaux, puits béants, accidents géologiques majeurs y sont en effet visibles, particulièrement sur les zones dénudées... Une fois sur place, ces
	documents seront également précieux pour préparer les explorations journalières et définir les itinéraires d’approche.</p>
