<p>En octobre 2015, en marge de son assemblée générale annuelle, Centre Terre tenait sa première réunion préparatoire en vue de
	l’expédition qui se déroulera en janvier et février 2017 sur l’île Madre de Dios. Depuis, de nombreux points ont bien avancé, il est donc temps de
	faire un point.</p>
<h3>L'équipe</h3>
<p>La constitution de l'équipe coté Français, est bouclée depuis le mois de novembre. Une dizaine de candidatures n’ont
	malheureusement pas pu être retenues, faute de place. Le choix a été difficile, il a fallu respecter de multiples critères contraignants, parmi
	lesquels: la motivation, la présence d’éléments moteurs, la complémentarité, les compétences indispensables, l’équilibre entre participants français
	et chiliens.</p>
<p>Au Chili, le process d'inscription en coordination avec les universités qui ont faite connaitre leur attachement au projet ainsi
	que leur volonté a collaborer débute à peine, il ciblera avant tout, des profils de spécialistes et de chercheurs définis comme prioritaires.</p>
<p>L'équipe déjà constituée s’est immédiatement mise au travail. Chacun doit s’investir personnellement dans la recherche des
	partenaires indispensables à l’équilibre financier du projet : environ 40 000 euros sont nécessaires pour boucler le budget prévisionnel, et nous
	sommes aussi à la recherche de partenaires techniques pour fournir du matériel (valeur monétaire estimée à 45 000 euros). Il faut également trouver
	des soutiens au Chili pour couvrir l'ensemble de nos besoins logistiques.</p>
<p>Pour nous tous, cette phase qui durera jusqu’au départ le 2 janvier 2017 est difficile et contraignante, mais elle conditionne la
	suite et aura sa récompense: une fois sur place, parcourir les grands lapiaz, explorer l’île jusque dans ses tréfonds afin de découvrir les richesses
	qu’elle comporte!</p>
