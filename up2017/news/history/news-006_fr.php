<h3>Le projet de base scientifique</h3>
<p>Une fois débarqués sur la rive nord du seno Barros Luco, il faudra y établir une construction dont la vocation sera double :</p>
<ul>
	<li>sur la durée, constituer une base scientifique destinée à accueillir des chercheurs venant conduire, en ce lieu vierge de toute empreinte
		humaine, les études scientifiques qu’autorise sa nature exceptionnelle ;</li>
	<li>à court terme, constituer un lieu de vie protégé des rigueurs du climat afin de garantir le mordant des équipes engagées sur le terrain.</li>
</ul>
<p>Il s’agit donc d’un objectif fondamental pour lequel aucune improvisation n’est possible. D’autant moins que le classement de
	l’île en tant que Réserve naturelle impose que l’impact sur l’environnement d’une telle construction soit le plus proche possible de zéro. L'équipe
	UP-2017 s'est donc entourée de compétences spécifiques: Natalia a sollicité deux amies proches, Cécilia Vera, architecte indépendante et Christina
	Ibars, experte en marketing du Cabinet d'architecture, IWAL Ltda. installé à Santiago. Toutes deux, ont été mandatées de la part de Centre Terre pour
	définir, en fonction d’un cahier des charges précis, les caractéristiques de la base scientifique, ainsi qu’un concept d’assemblage rapide et sûr
	pour son montage. Elle doit rechercher également les fournisseurs de matériaux capables d’assurer sa préfabrication puis sa gamme d'assemblage.
	Lorsque Cecilia, Christina et Natalia se sont engagées sur cette lourde responsabilité, elles n'avaient évidemment pas la prétention d'en assumer la
	totalité. En collaboration avec une enseignante, Cecilia a donc proposée ce projet atypique à l’Université de la Catolica comme un cours optionnel
	d'approfondissement dans le cadre de son unité spécialisée en architecture. Ce projet a été agréé par l’Université. C'est donc sur ce fondement
	qu'une classe d'étudiants recrutés en « Design d'architecture en zones géographiques isolées » — un intitulé ciblé sur notre projet de base
	scientifique — vient de commencer son travail en ce début de mois de mars.</p>
