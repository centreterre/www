<h3>L'île aux Glaciers de Marbre éditée au Chili</h3>
<p>En 2011 Centre Terre a confié à Georges la charge de raconter dans un beau livre nos vingt années d'explorations en Patagonie
	Chilienne. L’enthousiasme de toute l’équipe a permis le succès de la souscription indispensable à l’auto-édition de cet ouvrage. L’idée d’une
	traduction chilienne a rapidement vu le jour, avant même que le succès de l’édition française ne soit assuré.</p>
<p>Le but était double. D’abord, faire connaitre la spéléologie dans ce pays où sa pratique n’existe pas. Ensuite, disposer d’un
	moyen puissant pour diffuser l’idée qui s’est imposée à nous depuis l’année 2000 : parvenir un jour à l’inscription de l’île Madre de Dios, un milieu
	absolument unique au monde, au Patrimoine Mondial de l'Unesco.</p>
<p>Le chemin a été long, mais le résultat est maintenant là. En fin 2015, le Ministère des Biens Nationaux a signé avec Centre Terre
	le contrat d’édition. Natalia s’est chargée non seulement de toute la négociation avec les divers organismes officiels concernés au Chili, mais aussi
	de la traduction du texte en espagnol. L’ouvrage qui est maintenant sur le point d’être imprimé en commun avec le Sernatur, Service National du
	Tourisme au Chili, bénéficie d'une présentation signée de la main même du Ministre, M. Victor Osorio Reyes. Une partie de nos rêves devient
	aujourd'hui réalité.</p>
<p>La collaboration effective qui s’instaure ainsi entre Centre Terre et le Ministère des Biens Nationaux va continuer. Et l’un de
	ses buts sera cette candidature prochaine de Madre de Dios au Patrimoine de l'Humanité, un dossier qui est maintenant pris en main par les autorités
	chiliennes et auquel nous apporterons évidemment tout notre concours.</p>
<h3>Les préparatifs</h3>
<p>Ils sont en cours sur tous les fronts !</p>
<p>Une équipe pilotée par Florian s’est attelée à la remise en parfait état de l'ensemble des moteurs de notre flotte de Bombard...
	Ils devront tous être au top de leur forme pour leur mise en container courant septembre. Autour de Stéphane, une équipe établit et rassemble les
	documents cartographiques dont nous aurons besoin sur le terrain. Richard coordonne de son côté la mise sur pied d'un projet scientifique
	multidisciplinaire. Une autre équipe œuvre sur la couverture secours et médicale de l'expédition. D'autres membres ont mis en place les outils
	indispensables au suivi de la comptabilité de ce projet UP-2017, complexe du fait de la diversité des domaines qu’il touche. David et Olivier ont
	revu de fond en comble notre site internet. Thomas et Arnauld planchent sur un projet de financement coopératif… Bien entendu, les besoins
	spécifiques des camps avancés, des explorations souterraines, de la spéléo-plongée, ne sont pas oubliés: plusieurs équipiers ont la charge de
	quantifier les besoins logistiques et organisationnels propres à ces domaines.</p>
<p>Enfin, il y a notre projet scolaire, piloté par José, membre de Centre Terre mais aussi Conseiller Technique National de la
	Fédération Française de Spéléologie. Deux académies portent déjà ce projet, celles de Toulouse et Lyon. Des négociations sont actuellement en cours
	avec le ministère de l’Éducation Nationale à Paris. Un dossier plus complet est visible en suivant ce lien .</p>

