<p>Ce n'est pas tout ! En effet. Ce 18 mai passé, nous avions un important rendez-vous par visio conférence avec 3 des 9 groupes de travail de l'école
	d'architecture UC, afin que chacun d'eux puisse nous présenter l'état de leur projet. Des projets tous élaborés sur la base du cahier des charges
	établi par l'équipe Centre Terre, tenant compte des conditions climatiques, des impératifs logistiques et techniques, mais avec bien évidement toute
	la latitude possible pour eux en matière de concept, de développement et d'innovations. Soit près de 3h d'échanges qui furent au final extrêmement
	constructives pour tous avec des projets tous aussi exceptionnels les uns que les autres.</p>
<p>Ce mois de mai, c'est également le projet scientifique de l'équipe UP2017, qui a vu le jour. Un projet que nous avons voulu clair et ambitieux,
	qui sera bientôt consultable ici.</p>
<p>Bien entendu, hors de question de faiblir sur la communication et le partage, deux savoirs faires moteurs au sein de Centre Terre notamment en
	cette période ou il convient de trouver et rassembler tous les partenaires et financeurs incontournables au bon déroulement de ce projet.</p>
<p>Ainsi, Franck, assisté de Jean Marc et d'Olivier ont, pilotés sur le cinéma de Saint Girons toute une journée de projections/conférences. Un moment
	fort qui a rassemblé 280 élèves sur une journée et plus d'une cinquantaine de participants sur la soirée autour de la Patagonie. Dans le même
	registre, une nouvelle soirée de présentation / conférence ouverte au public est d'ores et déjà programmée avec la venue de Stéphane Jaillet sur
	Toulouse le 20 septembre prochain.</p>
<p>Toujours dans la communication, il y avait le projet de réaliser un film sur cette nouvelle aventure qui mijotait doucement. Centre Terre rêvait
	par ailleurs depuis bien longtemps, de faire un grand film passant les 52' sur ces formidables iles calcaires de Patagonie reprenant un peut la somme
	des travaux menés au coté d'une nouvelle aventure d'exception.... Et bien voilà que c'est maintenant acté ! Ce sera donc pour cette année avec Gilles
	Santantonio comme réalisateur en chef pour cette réalisation 2017. Une production que Gilles vient de concrétiser avec France 5. Soit un rêve qui
	devient réalité qui permettra de mieux partager encore nos aventures que ce site d'exception.</p>
<p>Coté logistique et finances du projet ... petitapeta ...</p>
<p>Grace aux bonnes relations entretenues par Marcelo, Centre Terre dispose d'ores et déjà, de l'indéfectible soutient de la CAP (Compagnie des Aciers
	du Pacifique) pour ce nouveau projet. Un partenaire fort de Centre Terre depuis 2006 qui se chargera une nouvelle fois cette année, aussi bien de
	convoyer nos deux containers (celui venant de France et celui comprenant le module base scientifique) depuis le port de Huachipato vers Guarello que
	mettre à disposition là, sur Guarello, une partie des installations minières pour l'accueil de l'équipe et de ses équipements. Au regard du projet
	2017, ce point "relais" est un incontournable logistique, aussi bien pour le matériel que les personnes qui seront nécessairement emmenés a faire un
	stop sur la base minière de la CAP, aussi bien a l'aller qu'au retour.</p>
<p>Bien entendu, en matière de logistique et partenariats, de très nombreuses choses avancent en parallèle.</p>
<p>Bien entendu, a ce stade, soit a près de 6 mois du départ, l'inlassable quête aux financeurs se poursuit avec ténacité. A ce stade, c'est près de
	la moitié du budget nécessaire qui est pourvu (Jo... a affiner la mesure) ...</p>
<p>Sur ce registre, nous venons pour la première fois de lancer une campagne de financement participatif. Une opération originale pour Centre Terre
	qui tient très sincèrement à remercier pleinement et publiquement l'ensemble des donateurs souscripteurs qui au travers de leurs apport emmènerons
	une aide certaine à ce projet 2017.</p>
<p>Et d'un plan pratique ...</p>
<p>Coté équipement, les approvisionnements s'organisent également. Qu'il s'agisse de matériel spéléo, de camp ou de bivouac, de cuisine, de vivres, de
	secours, médical, de matériel scientifique, nautique, de plongée et autres... Tout s'organise peut à peut sous l'œil aguerri des coordonateurs
	chargés de chaque registres. Cela, afin que tout soit fin près pour les 17 et 18 septembres, date a laquelle le container "France" se chargé puis
	fermé afin de pouvoir prendre la mer vers le Chili.</p>
