<h3>Financiamiento participativo</h3>
<p>Primero, concluyó la operación de financiamiento participativo lanzada el 18 de mayo por unos cuantos convencidos del equipo a través de la
	plataforma KissKissBankBank. Lo que fue un tímido inicio culminó el 18 de junio con ¡102 colaboradores! Este gran éxito ha permitido recaudar 8.500
	euros que servirán para financiar, en parte, la compra de los materiales de construcción y el traslado de la base científica hacia el seno Barros
	Luco, al norte del archipiélago Madre de Dios, objetivo de la expedición 2017.</p>
<p>Probablemente, Centre Terre no logre nunca agradecer lo suficiente a todos los mecenas, la mayoría de ellos, espéleos o simples apasionados de
	nuestro proyecto.</p>
<h3>Centre Terre y Chile : un trabajo de fondo</h3>
<p>En paralelo a esta operación, del 13 al 16 de junio Natalia y Marcelo estuvieron en Punta Arenas en una ronda de reuniones con instituciones y
	organismo privados. Este viaje, organizado con mucha antelación, permitió mantener encuentros importantes con las autoridades y órganos regionales,
	destacando el realizado a instancias del Intendente de la Región de Magallanes y la Antártica Chilena, don Jorge Flies Añón, al que acudieron el
	Gobernador de Última Esperanza, el Seremi de Bienes Nacionales, un representante de la Armada de Chile, la directora regional del Sernatur, la
	directora regional de CONAF, el Seremi de Cultura, entre otros.</p>
<p>Natalia y Marcelo hicieron una presentación de los 20 años de investigación de Centre Terre en los archipiélagos kársticos de la Patagonia chilena
	y de los principales trabajos publicados: documentales, publicaciones, artículos científicos, libros, etc. Los allí presentes quedaron impresionados
	por la magnitud de un trabajo que hemos realizado discretamente y durante años; una tarea realizada casi sin ninguna ayuda de los estamentos
	gubernamentales chilenos que hoy les ofrece en bandeja un elenco de riquezas naturales y culturales que permiten aspirar a la clasificación de los
	entornos kársticos que hemos explorado como patrimonio mundial de la humanidad.</p>
