<h3>Base científica</h3>
<p>En cuanto a la base científica, se han acabado de desmontar los bastidores de madera gentilmente donados por la Escuela de Arquitectura de la
	Universidad Católica… ¡o casi! Cecilia tiene el detalle exacto de la madera recuperada. Ha rearmado los planos de la base considerando este material.
	Esta compleja labor ha hecho necesaria una revisión completa del concepto de base científica, manteniendo las premisas iniciales: una superficie de
	unos 50 m2 de superficie habitable, durabilidad ante las inclemencias, selección de materiales con el menor impacto posible en el medio ambiente.</p>
