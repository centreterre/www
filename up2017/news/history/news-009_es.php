<h3>Pre-expedición</h3>
<p>Por último, desde la segunda quincena de julio se está preparando una pre-expedición de reconocimiento que involucrará a una parte del equipo. A
	principios de agosto se enviará un pequeño grupo al Barros Luco con el objetivo de identificar con precisión el futuro lugar de implantación de la
	base científica. A principios de enero de 2017, para que la operación «desembarque» sea lo más eficaz posible, habrá que haber definido antes el
	lugar exacto. Por parte de Centre Terre, participarán Natalia, Marcelo, Richard y Bernard, que tendrán un segundo cometido: presentar el proyecto a
	las autoridades chilenas que visitarán Madre de Dios y que aún no conocen los secretos de estas islas kársticas donde se practica la espeleología,
	una disciplina hasta la fecha prácticamente desconocida en Chile.</p>
<p>Esta pre-expedición será posible gracias al valioso apoyo de la Intendencia de la XII Región, la Gobernación de Última Esperanza, la Armada de
	Chile, el Sernatur Magallanes y la Seremi de Bienes Nacionales, quienes formarán parte de la comitiva que visitará Madre de Dios junto a más
	autoridades y representantes territoriales durante la operación de reconocimiento.</p>
<p>Al regreso del equipo a tierra, se están programando presentaciones y charlas para compartir con el público nuestro trabajo de décadas en los
	archipiélagos kársticos. Daremos más detalles en nuestro Facebook y Twitter.</p>
