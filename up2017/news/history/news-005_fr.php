<h1>Le film 2014 débute sa carrière</h1>
<h3>
	<i class="fa fa-clock-o"></i><?=Utils::i19n ( array ('fr' => 'Publié le','es' => 'Publicado el' ) )?> 30-12-2015	
</h3>
<p>Le film L’île aux Glaciers de Marbre réalisé par Luc-Henri Fage et produit par MC4 et Félis Production, durant l’expédition 2014 sur Diego de
	Almagro sera projeté samedi 26 septembre à 10 h 30 dans le cadre des rencontres internationales de plongeurs, qui auront lieu cette année dans le
	Lot. Laurent Mestre, Carlos Placido, Franck Bréhier et Joël Trémoulet seront sur place pour le présenter.</p>
