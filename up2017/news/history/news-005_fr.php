</p>
<p>Par ailleurs, ce film a été sélectionné pour le festival international du film d’aventure de Dijon Les Écrans de l’Aventure. Il y sera projeté le
	jeudi 8 octobre à 22 heures (Cinéma Olympia), ainsi qu’à 9 h le vendredi matin pour les scolaires (cinéma Darcy).</p>
<p>Enfin il sera diffusé en multi-diffusion sur Ushuaïa TV cet automne, la première fois le mardi 24 novembre à 20 h 40.</p>
