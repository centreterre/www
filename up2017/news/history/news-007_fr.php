<p>La base scientifique est l’élément central du projet d’expédition 2017. Elle servira de lieux de vie et de centre opérationnel pour les études
	scientifiques, les briefings et les communications. Conçue en partenariat avec les architectes chiliennes Cecilia Vera, du cabinet d'architecture
	IWAL, et Macarena Burdiles, sa conception est innovante et répond à des critères écologiques (matériaux dégradables et utilisation de bois local).</p>
