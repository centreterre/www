<p>En participant à la campagne de financement KissKissBankBank qui s’achèvera le 30 juin 2016, vous nous aiderez à la construire et à l’acheminer en
	kit sur l’île de Madre de Dios, oú nous consacrerons plusieurs jours sous la pluie à la construire.</p>
<p>Pour chacun de vos dons, Centre Terre vous propose une contrepartie clairement identifiée et proportionnée à l’ampleur de votre engagement ! A
	l’issue de l’expédition, la base que nous aurons construite restera en place pour servir de base scientifique permanente.</p>
