<h1>El film 2014 comienza su carrera</h1>
<h3>
	<i class="fa fa-clock-o"></i><?=Utils::i19n ( array ('fr' => 'Publié le','es' => 'Publicado el' ) )?> 30-12-2015	
</h3>
<p>La película La isla de los Glaciares de Mármol, realizada y producida por Luc-Henri Fage durante la expedición 2014 a la isla Diego de Almagro, se
	proyectará el sábado 26 de septiembre a las 10:30h en el marco de los encuentros internacionales de buceo, que este año se celebrarán en el
	departamento francés de Lot. La presentación de la película estará a cargo de Laurent Mestre, Franck Bréhier, Carlos Placido y Joël Trémoulet.</p>
