<p>Por otro lado, el film ha sido seleccionado para el festival de Dijon Les Écrans de l’Aventure. Se proyectará el jueves 8 de octubre a las 22:00h
	(cinema Olympia) y a las 09:00h el viernes para los más pequeños (cinema Darcy).</p>
<p>Además, el canal Ushuaïa TV emitirá la película este otoño. La primera ocasión será el martes 24 de noviembre a 20:40h.</p>
