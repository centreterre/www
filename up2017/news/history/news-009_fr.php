<p>Centre Terre ne remerciera jamais assez tous ces donateurs, pour bonne partie eux-mêmes spéléos ou simple passionnés par notre projet.</p>
<h3>Centre Terre et le Chili : un travail de fond</h3>
<p>
	Parallèlement à cette opération, Natalia et Marcelo se sont rendus du 13 au 16 juin à Punta Arenas pour rencontrer des partenaires institutionnels et
	privés. Ce déplacement avait été organisé longtemps à l'avance. D'importantes <b>réunions</b> avec les autorités et divers organes associés ont pu
	avoir lieu, principalement celle organisée sous la coordination de Jorge Flies Añón, intendente (préfet de région) de la Región de Magallanes et de
	l'Antártica Chilena, en présence de plusieurs autres services étatiques chiliens: le Gouverneur d'Última Esperanza, le Seremi des Biens Nationaux
	(représentant du Ministère sur la 12ème région), le Sernatur (service du tourisme), la Marine chilienne,le Seremi de Culture, CONAF, entre autres ...
</p>
<p>Natalia et Marcelo ont présenté les 20 années de travaux conduits par Centre Terre sur les Archipels karstiques de la Patagonie Chilienne, ainsi
	que les découvertes majeures et les innombrables productions qui en ont découlé : films, publications, et articles scientifiques, ouvrages.... De
	quoi impressionner nombre d'élus qui ont pu mesurer l'ampleur du travail que nous avons accompli dans l'ombre et sur la durée. Ce travail a été
	réalisé presque sans aucune aide des instances gouvernementales chiliennes ; aujourd'hui il leur offre sur un plateau un ensemble de richesses
	naturelles et culturelles permettant d'envisager un classement au patrimoine mondial de l'humanité des domaines karstiques que nous avons explorés.</p>
