<h3>Financement participatif</h3>
<p>A commencer par la clôture de l'opération de financement participatif, lancée le 18 mai par quelques convaincus au travers du site de
	KissKissBankBank. Elle a démarré timidement pour finalement s'achever le 18 juin avec 102 donateurs au compteur ! Une véritable réussite qui a permis
