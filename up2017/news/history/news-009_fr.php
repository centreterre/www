<h3>Pré-expédition</h3>
<p>Enfin, depuis la mi-juillet, c’est la préparation d'une pré-expédition de reconnaissance qui occupe une partie de l'équipe. L'objectif est de
	dépêcher début août une petite équipe jusqu'au seno Barros Luco afin de localiser avec précision le futur lieu d'implantation de la base scient
	ifique. Début janvier 2017, l’efficacité du "débarquement" des participants et de leur matériel exigera que le lieu précis ait été parfaitement
	défini à l’avance. Cette pré-expédition comprendra Natalia, Marcelo, Richard et Bernard, qui auront une seconde mission : présenter le projet à un
	certain nombre d'autorités chiliennes impliquées, qui ne connaissent pas encore tous les secrets de ces îles karstiques où se pratique une discipline
	encore inconnue il y a peu sur le Chili : la spéléologie ! Cette pré-expédition permettra enfin la tenue de diverses réunions dédiées à la
	préparation de l'expédition de 2017.</p>
<p>Cette pre-expédition, n'est possible que grâce à l'important soutien des services de l'Intendant de la XII Région, le gouverneur de Última
	Esperanza, l'armée du Chili, le Sernatur Magallanes et le Seremi de Bienes Nacionales, qui formeront le groupe d'autorités qui visiterons Madre de
	Dios accompagnés d'autres autorités et représentants territoriaux durant cette opération de reconnaissance.</p>
<p>De retour sur le continent, l'équipe tiendra plusieurs présentations et conférences actuellement en cours de programmation afin de partager ses
	dizaines d'années de travaux sur ces archipels karstiques, avec le public. Plus de détails à venir sur nos réseaux Facebook et Twitter.</p>
