<h3>Base scientifique</h3>
<p>Concernant la base scientifique, le démontage des éléments gracieusement offertes par l'université UC de Santiago est achevé - ou presque ! Cécilia
	dispose du décompte exact des bois disponibles. Elle a donc repris l'intégralité des plans de la base en tenant compte de cette donnée. Ce travail
	complexe a demandé une refonte intégrale du concept de la base scientifique - en conservant toutefois les principes de départ : une cinquantaine de
	mètres carrés de surface habitable, une durabilité dans le temps, une sélection de matériaux visant a préserver au mieux l'environnement.</p>
