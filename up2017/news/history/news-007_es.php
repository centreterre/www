<p>Colaborando en la campaña de financiamiento KissKissBankBank que finalizará el 30 de junio del 2016, nos ayudará a montar y
	transportar las piezas a la isla Madre de Dios, donde dedicaremos varios días a ensamblarlas bajo la lluvia.</p>
<p>Por cada donativo, Centre Terre le propone una contrapartida claramente identificada y proporcional a su aporte. Al final de la
	expedición, la cabaña que habremos montado permanecerá en el lugar para que sirva de base científica permanente.</p>
