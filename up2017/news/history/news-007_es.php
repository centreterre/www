<p>La base científica es el eje central del proyecto de expedición 2017. Nos servirá de lugar común y de centro operacional para el
	estudio científico, los briefings y las comunicaciones. Concebida gracias a la colaboración con las arquitectas chilenas Cecilia Vera, de la oficina
	de arquitectura IWAL, y Macarena Burdiles, su concepto es innovador y responde a los criterios ecológicos (materiales degradables y uso de madera
	local).</p>
