<p class="bodytext fwb">Une équipe très expérimentée</p>
<p>Avant son départ, toute expédition doit résoudre deux problèmes: définir ses objectifs et se donner les moyens de les atteindre.
	Mais cela passe au départ par une équipe franco-chilienne très solide, multidisciplinaire, dont le noyau dur connaît la région depuis 20 ans.
	Expériences communes en milieu extrême, compétences multiples et très forte motivation font sa principale force.</p>
<p class="bodytext fwb">Les objectifs</p>
<p>Ils sont clairs : malgré quatre expéditions successives montées par Centre Terre sur Madre de Dios, plus de la moitié reste
	quasiment inexplorée : il s’agit de la partie nord de l’île, délimitée au sud par le fjord Barros Luco et au nord par le canal Trinidad. Au total, ce
	sont plus de 200 km2 qui sont inconnus, si l’on excepte quelques très rares incursions principalement côtières. Ce qui a protégé la virginité de ce
	vaste espace, c’est son inaccessibilité. Par mer, l’approche est soumise à l’imprévisibilité de l’océan. Par terre, les distances sont trop grandes
	depuis le seul lieu habité : l’île de Garello et sa base minière. Il faudra donc forcer le passage par mer, se faire déposer sur la côte nord du
	Barros Luco — seul lieu un peu protégé — et construire une base scientifique, lieu de vie à l’abri du climat hostile de cette région du globe,
	caractérisé par la permanence et la violence de ses vents et de ses pluies.</p>
<p class="bodytext fwb">L’intendance</p>
<p>Rassembler les moyens pour atteindre les objectifs fixés constitue la partie la plus ingrate. Ces moyens sont de deux ordres : 1)
	financier, afin d’alimenter un budget que les contributions des seuls participants ne sauraient équilibrer, au vu des dépenses incompressibles
	qu’implique une expédition de cette envergure ; 2) logistique, afin d’établir les contacts et de rassembler les matériels, les hommes et les moyens
	techniques indispensables à l’achèvement des buts recherchés. Un travail de longue haleine, entrepris tant en France qu’au Chili depuis l’automne
	2015, et qui vise à résoudre tous les problèmes posés par ce vaste volet.</p>
<br>
<h2>Objectifs à atteindre</h2>
<ul>
	<li>Exploration et étude des principales résurgences</li>
	<li>Prospection, exploration et topographie des pertes et cavités du plateau</li>
	<li>Géographie physique et Sciences de la Terre : climatologie, hydrologie-hydrochimie, bathymétrie, géologie, géomorphologie, dépôts souterrains,
		paléoclimatologie...</li>
	<li>Sciences du Vivant : botanique, zoologie</li>
	<li>Géoarchéologie : sites kawésquar et contexte</li>
	<li>Communications : site internet-forum, visioconférences (avec les scolaires)</li>
	<li>Tournage et réalisation d’un film documentaire (TV, salle)</li>
	<li>Rassembler les critères UNESCO pour une future demande d’inscription</li>
</ul>
