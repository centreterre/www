<h2>Nous repartons</h2>
<p>Après vingt ans d’exploration et sept expéditions successives dans les îles calcaires de l’Archipel de Patagonie occidentale, nous
	avons découvert les Glaciers de Marbre, les plus grandes cavités d’Amérique australe, des espèces animales nouvelles, des peintures rupestres
	inconnues et les vestiges archéologiques des premiers habitants de ces contrées hostiles.</p>
<p>Nous avons parcouru l’Archipel de Madre de Dios et celui de Diego de Almagro, à la recherche de grottes et de gouffres. Nous y
	avons éprouvé le bonheur de la découverte, celui de l’exploration pure et la satisfaction d’avoir pu partager le fruit de nos travaux avec le plus
	grand nombre.</p>
<p>Pourtant, trop isolée, toute la moitié nord de Madre de Dios nous est restée inaccessible ! Par 50°10 de latitude sud, le fjord
	Barros Luco et son karst inexploré nous défient toujours. En 2006, 2008, et 2010, nous n’avons pu en effleurer que la rive sud, en profitant de
	fenêtres météorologiques étroites, en portant nos bateaux à travers la montagne ou grâce à des déposes héliportées par les armées française et
	chilienne.</p>
<p>Mais au nord, un plateau de 150 km2 est encore vierge de toute exploration : le potentiel de découverte y est exceptionnel. C’est
	pour nous confronter à ce challenge que nous retournons en Patagonie. Forts de l’expérience acquise lors de toutes ces expéditions, forts d’une
	équipe sans cesse renouvelée et rajeunie, forts de notre motivation, oui, nous repartons. Nous serons là-bas début 2017 pour y poursuivre quatre
	objectifs : découvrir, comprendre, partager, préserver.</p>
