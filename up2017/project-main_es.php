<p class="bodytext fwb">Un equipo muy experimentado</p>
<p>Antes de partir, todo el equipo debe resolver dos aspectos: definir los objetivos y dotarse de los medios para alcanzarlos. Para
	ello se parte de la base de un equipo franco-chileno muy sólido, cuyo núcleo duro conoce la región desde hace 20 años. Su principal punto fuerte son
	las experiencias en común en entornos extremos, las múltiples competencias y una gran motivación.</p>
<p class="bodytext fwb">Los objetivos</p>
<p>Están claros: pese a las cuatro expediciones sucesivas de Centre Terre a Madre de Dios, más de la mitad de la isla sigue casi sin
	haber sido inexplorada. Se trata de la parte norte, delimitada al sur por el seno Barros Luco y, al norte, por el canal Trinidad. Son en total más de
	200 km2 casi desconocidos, a excepción de algunas incursiones muy ocasionales, principalmente costeras. Lo que ha preservado la virginidad de esta
	vasta extensión es su inaccesibilidad. Por mar, la aproximación depende de un océano imprevisible. Por tierra, las distancias son demasiado grandes
	desde el único lugar habitado, la base minera de la isla de Guarello. De modo que no queda más remedio que forzar el paso por mar, que nos dejen en
	la ribera norte del Barros Luco (única zona un poco protegida) y construir una base científica que será nuestro lugar de vida protegido del hostil
	clima de esta región del globo, cuyas principales características son sus constantes y violentos vientos y la incesante lluvia.</p>
<p class="bodytext fwb">Medios</p>
<p>Reunir los recursos para alcanzar los objetivos fijados es la parte más difícil. Esto medios son de dos tipos: 1) económicos, con
	el fin de cumplir con el presupuesto, cosa imposible solo con las contribuciones de los participantes, dados los gastos asociados a una expedición de
	tal envergadura; 2) logísticos, con el objetivo de conseguir los materiales, los recursos humanos y técnicos indispensables para alcanzar la meta
	fijada. Es una labor de largo aliento que se viene acometiendo tanto desde Francia como desde Chile desde otoño del 2015 y que apunta a resolver
	todos los problemas asociados a este ambicioso proyecto.</p>
<br>
<h2>Objectivos</h2>
<ul>
	<li>Exploración y estudio de las principales resurgencias.</li>
	<li>Prospección, exploración y topografía de los sumideros y cavidades del altiplano.</li>
	<li>Geografía física y Ciencias de la Tierra: climatología, hidrología-hidroquímica, batimetría, geología, geomorfología, topografía de las
		cavidades, sedimentología de los depósitos subterráneos, paleo-climatología, etc.</li>
	<li>Ciencias Naturales: botánica, biología.</li>
	<li>Geo-arqueología: sitios kawésqar y contexto.</li>
	<li>Comunicación: sitio web-foro, videoconferencias (con los escolares).</li>
	<li>Grabación y realización de un film documental (TV, sala).</li>
	<li>Reunir los criterios UNESCO para una futura solicitud de inscripción.</li>
</ul>
