<h2>¡Volvemos!</h2>
<p>Después de veinte años de exploración y de siete expediciones sucesivas a las islas calcáreas del archipiélago de la Patagonia
	chilena, hemos descubierto los Glaciares de Mármol, las mayores cavidades de Sudamérica, nuevas especies de animales, pinturas rupestres desconocidas
	y vestigios arqueológicos de los primeros habitantes de estas hostiles tierras.</p>
<p>Hemos recorrido el archipiélago de Madre de Dios y el de Diego de Almagro, explorando cada rincón en búsqueda de cuevas y simas.
	Hemos experimentado la dicha del descubrimiento, de la exploración pura y la satisfacción de poder compartir el fruto de nuestros trabajos con el
	gran público.</p>
<p>No obstante, por su aislamiento, ¡toda la mitad norte de Madre de Dios se nos ha resistido! En la latitud 50°10 Sur, el seno
	Barros Luco y su karst inexplorado nos siguen desafiando. En 2006, 2008 y 2010 no pudimos más que acariciar la rivera sur, aprovechando las estrechas
	ventanas de buen tiempo, cargando nuestros botes a través de la montaña o bien gracias a los porteos en helicóptero de las armadas francesa y
	chilena.</p>
<p>Pero esa meseta de 150 km² sigue virgen, sin ser explorada: el potencial por descubrir es extraordinario. Por eso volvemos a
	Patagonia, para enfrentar ese reto. Con la experiencia acumulada durante todas las expediciones, con un equipo que se renueva y rejuvenece
	constantemente, sí, ¡volvemos! Estaremos allí a principios del 2017 para cumplir con cuatro objetivos: descubrir, comprender, compartir, proteger.</p>
