		<p>El Ministro de Bienes Nacionales, Víctor Osorio, anunció que un equipo de la fundación francesa Centre Terre, iniciará una pre expedición a la
			Isla Madre de Dios en la Región de Magallanes, con el objetivo de encontrar el lugar para emplazar un campamento donde se instalarán en el verano
			del 2017 para continuar las investigaciones con las cuales se obtendrán datos para postular este lugar como Patrimonio de la Humanidad.</p>
		<p>“Con el desarrollo de esta importante expedición científica, llamada Última Patagonia, podremos conocer de primera fuente las potencialidades de
			este desconocido territorio que, sin duda, será un gran aporte para la región más austral del planeta”, señaló el ministro Osorio.</p>
		<p>El equipo de especialistas estará encabezado por el Director Científico de Centre Terre, Richard Maire; el Jefe de la expedición Francia, Bernard
