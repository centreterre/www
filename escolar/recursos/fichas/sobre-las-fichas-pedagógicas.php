<h1>Sobre las fichas pedagógicas</h1>
<div class="worksheets">
    <p>Las fichas pedagógicas que ponemos a disposición no han sido estandarizadas al currículo escolar con el objetivo que puedan ser usadas por
        escolares de ambos ciclos de primaria. Se han articulado tomando como base las fichas en bruto, una problemática puntual, preguntas precisas o
        bien las presentaciones realizadas por participantes chilenos. El material pedagógico cubre numerosas disciplinas y están pensadas para que
        cada docente encuentre una fuente de inspiración sobre la que trabajar.
    </p>

    <p>El material de apoyo consta de:</p>
    <ul>
        <li>Un conjunto de fichas con datos en bruto</li>
        <li>Una base fotográfica</li>
        <li>Una base topográfica</li>
        <li>Un conjunto de mapas</li>
        <li>Presentaciones con imágenes y/o voz</li>
    </ul>
    <p>En cuanto a la metodología pedagógica propuesta, las fichas pretenden establecer un punto de equilibrio entre un proceso científico en el que
        el alumno es guiado paso a paso y un proceso científico en el que el alumno deberá demostrar mayor grado de autonomía para resolver un
        determinado problema.
    </p>
    <p>La mayor parte de las fichas se basan en la experiencia y lo aprendido por los equipos de expedición de Centre Terre. Pueden constituir una
        lección en sí o integrarse en otra materia. Pueden usarse parcialmente o modificarse en función de las necesidades de los estudiantes. Se
        trata de apoyos pedagógicos que guardan estrecha relación con las expediciones de los espeleólogos de Centre Terre en las islas kársticas de
        la Patagonia chilena y en Campo de Hielo Sur.
    </p>
    <p>Con el objetivo de que las fichas pedagógicas en español puedan ser usadas tanto por las clases de Chile como por las de Francia, hemos
        conservado la clasificación siguiendo los ciclos franceses (C2, C3, C4) pero indicando la correspondencia de la clase según el sistema chileno
        (1º, 2º, 3º, etc).
    </p>
</div>

