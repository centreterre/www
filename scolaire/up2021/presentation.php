<h1>Suivre l’expédition Ultima Patagonia 2021 avec vos élèves</h1>
<p>Forte des découvertes des expéditions précédentes, l’équipe de Centre Terre retourne à Madre de Dios en janvier et
    février 2021 pour poursuivre ses explorations.</p>
<p>Vous avez été nombreux à suivre le projet scolaire en 2019, et pour vous permettre d’aller encore plus loin, nous
    vous proposons de réitérer l’expérience, ou tout simplement de nous rejoindre pour la première fois dans cette
    nouvelle aventure.</p>
<p>En partenariat avec le Ministère de l’Éducation Nationale et la Fédération Française de Spéléologie, nous vous
    invitons à participer à ce projet scolaire.</p>
<p>Toutes les classes des établissements de France peuvent suivre les explorations et les découvertes faites durant
    l’expédition. En fonction des thématiques qui l’intéressent plus particulièrement, l’enseignant pourra utiliser les
    ressources de Centre Terre comme support pour construire avec ses élèves des séquences pédagogiques.</p>
<p>Le suivi de cette expédition, qui a le statut d'expédition nationale de la Fédération Française de Spéléologie,
    permet un travail interdisciplinaire en sciences de la vie et de la terre, en physique-chimie mais aussi en
    histoire-géographie, français, espagnol, anglais, arts plastiques ou éducation physique et sportive. Il contribue à
    l'éducation par le numérique et participe au développement de la culture scientifique et technique en permettant aux
    élèves de vivre pleinement l'aventure de la science. Enfin, il véhicule des valeurs de solidarité et de dépassement
    de soi inhérentes aux activités d’exploration.</p>
<p>De même, dans les mises en œuvre et dans les démarches entreprises, Centre Terre initie à l’éducation au
    développement durable et sensibilise à la préservation de l’environnement et à la gestion des ressources.</p>
<p>Pour suivre l’expédition, Centre Terre met à disposition une multitude de supports et de moyens de communication :
    Espace scolaire sur le site de Centre Terre, Forum de discussions, fiches ressources, films documentaires de France
    5 et d’Arte, ainsi que des visioconférences qui se dérouleront pendant l’expédition.</p>
<p>La spécificité de cette aventure humaine repose sur l’éclectisme des scientifiques qui contribuent aux recherches
    ainsi qu’aux nombreux domaines de compétences de tous les membres du groupe. Adhérer au projet scolaire, c’est se
    projeter au cœur des éléments, dans un environnement difficile, aux confins de territoires peu connus pour faire
    vivre de manière active, la géologie, l'hydrologie, la climatologie, la paléontologie, l’art rupestre,
    l'archéologie, l'écologie, la géographie, la glaciologie... et bien d’autres disciplines encore.</p>
<p>Tous les participants de l’expédition ont à cœur de faire partager et de rendre accessible au plus grand nombre, les
    connaissances mises en œuvre et les observations réalisées pour susciter la curiosité et stimuler l’envie de
    découvrir. Centre Terre a à cœur de mettre en avant les valeurs éducatives que sont l’entraide et la coopération
    induites par la pratique de la spéléologie.</p>
<p>D’ores et déjà, les ressources mises en lignes peuvent servir au travail préparatoire des enseignants souhaitant
    s’approprier le projet et l’utiliser comme support pédagogique dans les apprentissages de leurs élèves ainsi que
    dans les acquisitions de compétences disciplinaires ou pluridisciplinaires.</p>
<p>Ces ressources seront complétées et enrichies au fur et à mesure de l’avancée de l’expédition.</p>
<p>Les classes qui souhaiteraient pouvoir finaliser le travail de l’année en bénéficiant d’une sortie spéléologie sur le
    terrain avec des membres de l’expédition doivent s’inscrire au concours piloté par l’académie de Toulouse.</p>
<p>Ce concours, ouvert à toutes les classes, de toutes les académies primera les projets témoignant d’un investissement
    réel par l’intermédiaire d’une production originale. Cette production peut se faire sous différentes formes mais
    devra être en lien avec les contenus abordés avant, pendant et après l’expédition. Les classes lauréates se verront
    récompensées par une sortie spéléologie.</p>
<h1>Avant l’expédition : (septembre 2020 à janvier 2021)</h1>
<p>Dès la rentrée de septembre les classes intéressées peuvent s’affilier au projet en s’inscrivant sur le site du
    rectorat de l’Académie de Toulouse. Elles pourront, via le site de Centre Terre, suivre tous les préparatifs de
    l’expédition. De même, à cette période sera activé le forum de discussions sur lequel de nombreux échanges pourront
    être faits en vue de répondre aux questions des élèves et des enseignants.</p>
<p>Pendant l’expédition (janvier -février), les classes pourront suivre, presque en direct, le déroulement de
    l’expédition par l’intermédiaire du site et utiliser le forum comme support d’échanges avec les membres de
    l’expédition.</p>
<p>Une ou deux visioconférences seront aussi organisées pendant cette période en plusieurs points de l’académie de
    Toulouse.</p>
<p>Après l’expédition (février à juin), le jury évaluera les productions des classes ayant participé au concours, et ce
    dans plusieurs catégories.</p>
<p>Le concours primera les classes au niveau académique et au niveau national pour le primaire et le secondaire. Les
    classes lauréates bénéficieront d'une journée de spéléologie encadrée par les spéléologues de Centre Terre, ce qui
    permettra de finaliser le projet et récompensera le travail d’une année.</p>
