<h1>L’intérêt d’une nouvelle expédition en Patagonie en 2023 ?</h1>
<h2>Petit préambule</h2>
<p>Si aujourd’hui la totalité de la planète semble avoir été explorée, en réalité ce n’est pas tout à fait vrai.
    Heureusement subsiste des lieux où personne ne s’est encore aventuré. Certes ces endroits sont devenus rares, et
    restent préservés du fait de leur inaccessibilité. (Grandes profondeurs océaniques, sommets très élevés et isolés,
    gouffres et abimes, quelques coins de déserts et de forêts primaires…)</p>
<p>Mais ces lieux voient malheureusement leur taille se réduire chaque jour un peu plus, d’où l’importance de les
    explorer et de les étudier avec respect, et dans un but de préservation. Les bouleversements climatiques et
    géographiques accélèrent plus encore l’urgence de ces explorations dont l’enjeu et de découvrir des richesses
    naturelles encore méconnues et les protéger avant même qu’elles ne disparaissent. L’enjeu actuel est bien là, ne pas
    faire disparaitre ce que nous ne connaissons pas encore.</p>
<p>Initiées par une poignée de scientifiques les premières expéditions de reconnaissance ont progressivement laissé
    place à des équipes plus nombreuses au champs d’investigation plus large et la logistique plus conséquente pour
    aller toujours un peu plus loin. La conjugaison des compétences est bien une des caractéristiques de Centre Terre et
    c’est là, la clef de l’obtention de résultats toujours plus complets et embrassant des champs de connaissances
    toujours plus vastes.</p>
<p>Tant qu’il y a des choses à découvrir, il y a des envies d’exploration, des besoins de connaissances, des aventures à
    vivre, et beaucoup à partager.</p>
<h2>Les motivations profondes</h2>
<p>Pourquoi donc s’acharner ainsi sur cette région insulaire depuis plus de 20 ans ? Il y a plusieurs raisons. Il faut
    d’abord un petit groupe, un noyau dur de gens passionnés. Une chose est sûre : il y a un sentiment ancré chez tout
    être humain depuis toujours, c’est la curiosité́, aller où personne n’est allé́. Ce sentiment est très fort chez
    les spéléologues puisque nous sommes pour la plupart des explorateurs du monde souterrain. Il y a aussi ce désir de
    vivre et revivre ensemble des histoires uniques dans des territoires lointains, sauvages et d’une esthétique à
    couper le souffle. Car notre monde moderne, souvent trop artificiel, nous incite à revenir à l’essentiel : la
    terre, la roche, l’eau, l’air, les plantes, les animaux, les insectes, les poissons, les mammifères marins comme les
    dauphins et les baleines, tout ce monde minéral et vivant sans lequel nous ne pouvons exister. A savoir les
    géosystèmes et les écosystèmes.</p>
<h2>De la vraie géographie</h2>
<p>En découvrant de nouveaux territoires, de nouveaux phénomènes, de nouvelles grottes, chaque participant fait œuvre de
    géographe et de scientifique au sens noble du terme, et contribue à faire progresser la connaissance. Chaque
    participant, même s’il n’est pas forcément un scientifique de profession, est un chercheur qui s’ignore. La science,
    c’est à dire la connaissance, appartient à toutes et à tous, c’est un bien commun qu’il faut développer et
    partager.</p>
<p>Nous faisons donc d’abord de la vraie géographie au sens large du terme. Rappelons que la géographie est une des
    sciences les plus anciennes avec l’astronomie et les mathématiques. Elle remonte à plusieurs millénaires et elle
    est plus que jamais d’actualité́. Mais nous élargissions aussi la recherche aux autres disciplines que sont les
    sciences de la vie et de la terre, mais aussi à l’archéologie car cette région si hostile a pourtant été parcourue
    par les Kaweskars, les « Nomades de la Mer » depuis des temps très anciens (5 à 6 000ans). Leurs adaptations
    physiologiques à ce milieu étaient remarquables. La Culture de ces premiers Patagons bien que matériellement
    réduite à l’essentiel a laissé des traces disséminées un peu partout dans les îles et où parfois les indices qui en
    témoignent sont discrets mais bien réels. Ces peuples premiers sont encore méconnus, et il reste donc encore
    beaucoup à découvrir à leur sujet.</p>
<h2>Une solidarité avec la nature et le vivant</h2>
<p>Cette connaissance de notre planète dans les recoins les plus éloignés et les plus hostiles, montre que celle-ci est
    reliée de toute part, notamment par les échanges entre l’atmosphère et les océans. Il est vrai que les pollutions
    semblent faibles en Patagonie, mais il est possible de découvrir des débris de plastique sur la côte pacifique.
    L’activité économique y est très réduite mais elle a déjà un impact sur les milieux. C’est en effet dans ces
    contrées isolées que les changements ont des conséquences les plus brutales et que les pollutions les effets les
    plus délétères.</p>
<p>Tout chercheur passionné a une forte empathie pour la nature et ses arcanes, et notamment pour le monde vivant. Mais
    cela est vrai aussi pour tout être humain qui prend le temps de regarder, d’observer, un peu comme un enfant qui
    s’extasie devant le monde qui l’entoure. En retournant à Diego de Almagro puis à Madre de Dios, nous savons qu’il
    reste encore beaucoup à découvrir car le territoire est difficile d’accès, la progression à pied sur les «
    glaciers de marbre » et la forêt Magellanique est un défi permanent. Parcourir les moraines et les glaciers dont les
    mouvements s’accélèrent est une gageure. Mais c’est justement cette difficulté́ qui est une motivation. Cette
    recherche scientifique va à l’encontre de la mode actuelle qui consiste à changer de programme de recherche tous
    les 4 ou 5 ans. Les grandes découvertes scientifiques se font de plusieurs façons : aller dans des lieux et des
    directions non prévus, mais aussi être patient et savoir approfondir le sujet. Être très spécialisé́ est
    indispensable (par exemple un entomologiste spécialiste des coléoptères), mais il faut aussi faire le « pont » entre
    les disciplines, c’est la « transdisciplinarité́ ». Par exemple, il faut savoir faire le pont entre la végétation et
    l’évolution du climat. Il faut « remonter le temps » et savoir interroger le temps court et le temps long ( temps
    géologique).</p>
<p>Que se passe-t-il quand une période glaciaire arrive ? La végétation est-elle détruite ou va-t-elle migrer ailleurs.
    Il en est de même pour les espèces animales. Les grottes vont-elles servir de refuges ? Les stalagmites vont-elles
    se développer ou pas ?</p>
<h2>L’union fait la force, pas la concurrence</h2>
<p>En fait Centre Terre avec l’expédition Ultima Patagonia 2023 a pour ambition de partager avec celles et ceux qui ne
    peuvent être sur place, une démarche de recherche en lien directe avec les observations de terrain faites au cœur
    d’une exploration. Il s’agit de construire une démarche déductive avec des outils d’analyse scientifiques. La
    performance technique et sportive est ainsi mise au service de la science. C’est en ce sens une véritable démarche
    de sciences participatives, et d’appropriation des savoirs.</p>
<p>Ensuite sur un plan scientifique au sens large, ces expéditions permettent à des jeunes chercheurs, et notamment des
    jeunes universitaires chiliens de venir, soit poursuivre, approfondir ou compléter leurs recherches. Nous devons
    collaborer. Sans cette collaboration, rien n’est possible. Le mot collaboration est fondamental. En effet, pour
    réaliser ce type d’expédition, il est indispensable de faire appel à de multiples compétences et de nombreuses
    ressources. Là encore le caractère atypique de cette expédition repose sur un savant dosage de mise en œuvre
    associative (Centre Terre, les fédérations sportives, comités, clubs), d’institutions de recherches (CNRS CNES), de
    partenaires publics (Éducation Nationale) et privés, œuvrant en synergie pour faire vivre le volet scolaire
    notamment.</p>
<h2>Faire découvrir pour mieux protéger</h2>
<p>Malgré́ les motivations diverses et complémentaires évoquées plus haut, l’une d’elle est très importante. Elle
    consiste à montrer, comme nous l’avons dit au début, que notre planète connait une certaine finitude. Le temps est
    révolu où l’homme se sentait perdu sur une planète immense. Nos milieux naturels ont été́ morcelés, fragmentés,
    réduits, dégradés, à cause de la surexploitation des ressources et de la croissance démographique. Mettre un
    couvercle de protection sur Madre de Dios comme celui de « Patrimoine de l’Humanité́ », serait une très bonne chose,
    et nous tenons à appuyer la demande du Chili auprès de l’UNESCO à travers nos recherches. Mais il faut aller
    encore plus loin et convaincre à travers les films, les publications, les réseaux divers que le statut UNESCO ne
    suffit pas pour protéger les milieux naturels. La crise sanitaire du Covid 19 est en grande partie liée au
    morcellement et la réduction des habitats de la faune sauvage. Cette crise sanitaire ne fait que mettre en lumière
    l’importance du changement de modèle sociétal et d’exploitation des ressources naturelles.</p>
<p>Les dimensions écologiques et sociales sont les deux versants d’une même montagne. C’est pour cette raison que tout
    chercheur doit se poser cette question : pourquoi je fais cela et quelle est son utilité́. C’est ce que nous
    essaierons de montrer notamment dans le futur film documentaire.</p>
<h2>Chronologie des principales découvertes en Patagonie</h2>
<ul>
    <li>1994 : Santiago, un géographe chilien nous remet un article de Cecioni sur les karsts chiliens qui mentionne la
        présence de calcaire dans les archipels de Patagonie.
    </li>
    <li>1995 : une première reconnaissance a lieu avec 4 membres de Centre-Terre. On découvre les premiers « glaciers de
        marbre » sur l’île Diego de Almagro et ses sculptures de dissolution.
    </li>
    <li>1997 : 1ère expédition spéléo-géographique sur Diego de Almagro. Exploration de la perte de l’Avenir et
        première plongée spéléo en siphon.
    </li>
    <li>2000 : 1ère expédition sur l’archipel Madre de Dios (MDD). Découverte des formes hydro-éoliennes : les «
        comètes de roche ». Exploration de la cavité́ la plus profonde. Sépultures Kaweskars avec crâne daté de plus de
        4000 ans.
    </li>
    <li>2006 : 2ème expédition sur MDD. Découverte de la grotte Pacifique présentant les 1ères peintures rupestres des
        archipels. Étude de la grotte glaciaire de la Moraine.
    </li>
    <li>2008 : 3ème expédition sur MDD. Étude du cimetière marin de la grotte de la Baleine, les ossements sont datés
        de plus de 3200 ans. Station hydro-météo sur l’île de Tarlton. MDD devient officiellement une réserve
        naturelle protégée.
    </li>
    <li>2010 : 4ème expédition sur MDD. Découverte des « champignons » exceptionnels du camp 2, témoins de records du
        monde de dissolution superficielle.
    </li>
    <li>2014 : 2ème expédition sur Diego de Almagro. Construction de la 1ère base-refuge. 1ère instrumentation des «
        comètes de roche ». Découverte d’une nouvelle espèce de fougère.
    </li>
    <li>2017 : 5ème expédition sur MDD et 1ère exploration de la partie nord. Construction de la base scientifique.
        Découvertes de 2 longues grottes côtières avec varves glaciaires + suivi de la dissolution superficielle
        (modélisation).
    </li>
    <li>2019 : 6ème expédition sur MDD. 1éré exploration du glacier Tempanos et explorations des premières cavités
        glacières. Découverte de l’abondance de Coraux dans les eaux de MDD. Prélèvement de concrétions et de sédiments
        lacustres permettant de mieux connaitre les Paléoclimats de la région.
    </li>
</ul>