<h2>Modalités du suivi de l'expédition Ultima Patagonia 2019</h2>
<hr>
<h3>Inscriptions</h3>
<p>Les inscriptions au suivi de l’expédition « Ultima Patagonia 2019 » sont gérées par la DAAC du rectorat de Toulouse
    par l’intermédiaire du lien suivant :</p>
<p>
    <a href="https://disciplines.ac-toulouse.fr/daac/ultima-patagonia-2019" target="_blank">https://disciplines.ac-toulouse.fr/daac/ultima-patagonia-2019</a>
</p>
<h3>Calendrier</h3>
<p>
    <b>Mai 2018</b> : ouverture de l’espace scolaire du site de Centre-Terre
</p>
<p>
    <b>31 octobre 2018</b> : clôture des inscriptions pour les classes ou groupes participants.
</p>
<p>
    <b>Du 3 janvier au 4 mars 2019</b> : expédition Ultima Patagonia 2019 sur l’île de Madre de Dios
</p>
<p>
    <b>Dates à déterminer</b> : visioconférence avec les membres de l’expédition Ultima Patagonia 2019
</p>
<p>
    <b>30 avril 2019</b> : date limite d’envoi des productions pour le concours
</p>
<p>
    <b>Début mai 2019</b> : jury d’attribution des prix pour le concours
</p>
<p>
    <b>Fin mai - début juin 2019</b> : sorties de spéléologie pour les classes lauréates du concours
</p>
<h3>Concours</h3>
<p>
    Pour consolider leur travail collectif, les classes ou les groupes participant au projet sont invités à réaliser une
    <b>production de leur choix.</b> Un jury composé de membres de Centre-Terre, de représentants de l’Éducation
    nationale et des principaux partenaires dont la Fédération Française de Spéléologie examinera ces réalisations. Le
    jury primera deux productions au niveau de l’académie de Toulouse et deux au niveau national pour l’enseignement
    primaire et secondaire. Les classes lauréates se verront offrir une journée de spéléologie, encadrée par
    Centre-Terre.
</p>
<p>
    Le thème de la production peut être très large : « La ressource en eau », « la spéléologie sur les archipels de
    Patagonie »… ou plus ciblé : « le peuple kawésqar » ou encore «Madre de Dios est-elle à l’abri de toute pollution ?
    ». Sa forme est totalement libre : panneau, affiche, carnet de voyage, BD, vidéo, maquette, livre électronique… En
    revanche, elle devra être valorisée par la <b>réalisation d’un diaporama</b> pour être présentée au jury. Ce
    diaporama devra rendre compte à la fois de la démarche, du suivi de l’expédition tout au long de l’année et de son
    aboutissement, c'est-à-dire la production finale réalisée par les élèves.
</p>
<p>
    La date limite d’envoi des productions est fixée au <b>30 Avril 2019</b>.
</p>
<h3>Coûts</h3>
<p>L’inscription et la participation au projet sont gratuites.</p>
<p>Les coûts de déplacement pour la visioconférence sont à la charge des établissements participants.</p>
<p>La classe lauréate du concours devra financer le déplacement jusqu’au lieu de pratique de la journée de spéléologie
    qui sera choisi au plus proche de l’établissement.</p>
<h3>Formation</h3>
<p>
    Pour les enseignants de l’académie de Toulouse qui le souhaitent, une journée de formation aura lieu à la <b>Maison
        pour la science au service des professeurs</b> de l’académie de Toulouse. Cette formation comprendra une
    présentation de l’expédition par des membres de Centre-Terre, un apport scientifique et des réflexions sur son
    utilisation pédagogique et culturelle. Elle fera l’objet d’une convocation sans remboursement de frais de
    déplacement.
</p>
