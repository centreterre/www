<h1>Finalisation des projets de suivi d’Ultima Patagonia 2023</h1>
<div class="row">
    <div class="col-md-12"><p>Avec le retour de toutes les équipes et l’arrivée très prochaine du conteneur, c’est bien
            la dernière phase d’UP23 qui s’amorce. Le retour du matériel, l’entretien et les réparations ainsi que le
            conditionnement qui s’en suit ne seront pas une mince affaire, mais un incontournable dans la perspective de
            nos futurs projets. Bien que chacun soit revenu dans les temps, l’esprit de beaucoup d’entre nous est encore
            là-bas et déjà les perspectives des futures explorations nous animent. La rédaction du rapport d’expédition
            a commencé, et l’analyse des très nombreux échantillons collectés est en cours. Elle livre chaque jour,
            petit à petit, un peu plus ses secrets.</p>
        <p>Avec la fin de l’année scolaire qui approche à grands pas, ce sont aussi de nombreux travaux scolaires qui
            s’achèvent. Les classes impliquées dans des démarches de projet ont pour beaucoup abouti à de très belles
            créations. Au total 20 établissements se sont inscrits sur la plateforme du rectorat de l’Académie de
            Toulouse. Cela représente près de 40 classes et 942 élèves allant de l’école primaire jusqu’au lycée. De
            très nombreux élèves se sont impliqués au travers de productions riches et variées et sans cesse renouvelées
            depuis que le volet scolaire des expéditions Centre Terre a vu le jour. Nous les en remercions vivement. Les
            productions témoignent d’une très grande créativité, d’une appropriation de connaissances et d’outils
            méthodologiques par les élèves, accompagnés par leurs enseignants. La très grande qualité des productions a
            rendu la tâche difficile aux différents jurys pour départager les classes et désigner les lauréates. Cette
            année deux catégories ont été définies au regard des dépôts des dossiers : une classe pour le primaire et
            une classe pour le secondaire.</p></div>
</div>
<h4>Pour la catégorie « écoles élémentaires »</h4>
<div class="row">
    <div class="col-md-4"><a title="" class="fancybox" rel="group" href="scolaire/up2023/001.png"><img
                    class="img-responsive" src="scolaire/up2023/001.png" alt=""></a></div>
    <div class="col-md-8"><p>C’est l’école de la Prairie à Toulouse qui remporte le concours. Cette production reflète
            un beau travail développé tout au long de l’année. L’approche est pluridisciplinaire à la fois technique,
            scientifique et s’inscrit dans une démarche d’éducation au développement durable. En effet, la réflexion sur
            la notion de patrimoine et la nécessité de sa protection mise en avant sur ce projet sont un bel exemple de
            sensibilisation des plus jeunes aux enjeux actuels. Le projet met l’accent sur la richesse et la fragilité
            de la bio- et la géo-diversité de Madre De Dios. Pour la réalisation du projet, la classe a exploité
            diverses thématiques et ressources proposées par Centre Terre à travers les fiches pédagogiques, les photos,
            le suivi d’UP2023 ainsi que l’utilisation des archives des expéditions antérieures, montrant ainsi un
            travail approfondi. Le carnet de voyage présente de jolis dessins, le contenu du texte est bien travaillé
            autant que l’expression orale. Se mettre dans la peau des explorateurs pour élaborer le récit d’aventures et
            de souvenirs, est une fabuleuse idée pour développer les rêves et la curiosité chez l’enfant, créant
            peut-être aussi des vocations de futurs explorateurs ! Pour avoir suscité à travers ce carnet de voyage, le
            goût de la découverte, de l’exploration et du partage, qui sont aussi les valeurs fondamentales de Centre
            Terre, notre choix s’est préférentiellement orienté sur la production de cette classe-là.</p></div>
</div>
<h4>Pour les établissements du secondaire</h4>
<div class="row">
    <div class="col-md-8"><p>C’est le lycée Marengo à Toulouse qui gagne d’extrême justesse le concours. Une production
            d'une grande qualité. L’implication de plusieurs matières (ce qui n’est pas simple dans le secondaire !) est
            à souligner. Cette production fait ressortir un travail très approfondi tout au long de l’année sur le suivi
            de l’expédition Ultima Patagonia (utilisation des ressources mises à disposition par Centre Terre,
            participation à la visioconférence, exploitation des archives des expéditions précédentes, etc…), et cela
            dans l’ensemble des disciplines abordées. Sur la forme, la production est réalisée sur un support technique
            interactif et ludique, facile à utiliser, et visuellement très esthétique. Techniquement, le niveau de la
            réalisation de cette production est impressionnant ! La création de l’escape game comme outil didactique
            permet l’apprentissage de manière ludique. Il en ressort d’ailleurs l’implication des élèves dans les
            différentes étapes de construction de ce jeu.</p></div>
