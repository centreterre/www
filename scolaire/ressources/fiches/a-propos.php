<h1>A propos des fiches pédagogiques</h1>
<p>Ces fiches n'ont pas été standardisées de manière à permettre une utilisation très large par les scolaires du cycle 2 au lycée. Elles sont
	articulées autour de données brutes, d'une problématique ou de questions précises. Elles couvrent de nombreux champs disciplinaires et chaque
	enseignant devrait y trouver source d’inspiration pour les exploiter. Elles s’appuient sur :</p>
<ul>
	<li>Un dossier photos</li>
	<li>Un dossier topographies</li>
	<li>Un dossier cartes</li>
</ul>
<p>Tous les éléments de ces dossiers peuvent aussi être utilisés pour les productions de classe.</p>
<p>En ce qui concerne la méthode pédagogique proposée, ces fiches sont un compromis entre une démarche scientifique où l'élève est guidé pas à pas et
	une démarche scientifique où l'élève devra faire preuve d'une plus grande autonomie pour répondre au problème posé.</p>
<p>La plupart sont en prise directe avec les découvertes faites par les spéléologues de Centre-Terre. Elles peuvent faire l'objet d'une leçon ou être
	incluses dans une leçon. Elles peuvent être utilisées pour partie ou modifiées en fonction des besoins des élèves. Ce sont des supports pédagogiques
	en prise directe avec les expéditions des spéléologues de Centre Terre sur l’archipel de Patagonie chilienne.</p>
