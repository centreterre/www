    <div class="col-md-6"><p>Para Centre Terre es una enorme satisfacción que el proyecto educativo haya ido creciendo
            de año en año. Desde 2010, en nuestra página web tenemos un foro exclusivo para los centros educativos, un
            apartado con fichas pedagógicas y hemos realizado videoconferencias para comunicarnos con los alumnos
            durante las expediciones. Varios expedicionarios dedican parte de su tiempo a visitar a las clases antes o
            después de la expedición, contarles sobre su experiencia y responder a las preguntas de los niños, que
            pueden versar sobre el día a día en terreno o bien sobre los descubrimientos científicos.</p></div>
</div>
<div class="row">
    <div class="col-md-12"><p>Esta inversión es beneficiosa para ambas partes y muy enriquecedora, tanto para los
            exploradores como para los escolares.</p>
        <p>El jueves 23 de mayo de 2019, en el rectorat de l’académie de Toulouse (consejo rector de la circunscripción
            educativa de Toulouse), se reunió el jurado para elegir a los ganadores y organizar las salidas
            espeleológicas con las clases. El jurado estuvo compuesto por:</p>
        <p>- Bernard TOURTE, jefe de expedición</p>
        <p>- Élodie MULOT, responsable del proyecto escolar en Centre Terre</p>
        <p>- Damien CHIGOT, Consejero Técnico Nacional de la Federación francesa de Espeleología</p>
        <p>- Valérie BOUKBEKER, encargada de las acciones culturales en el rectorat de Toulouse</p>
        <p>Tras varias horas de deliberación, definieron los cuatro trabajos ganadores.</p></div>
