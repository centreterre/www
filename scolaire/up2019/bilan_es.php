<h1>Balance del proyecto escolar 2019</h1>
<div class="row">
    <div class="col-md-12"><p>Desde 2008, Centre Terre ha forjado una estrecha relación de colaboración con la Éducation
            Nationale, el Ministerio de Educación de Francia, con el objetivo de que un número cada vez mayor de
            escolares puedan seguir las expediciones y vivir las aventuras de la asociación desde la escuela. El
            objetivo es doble: por un lado, organizar proyectos pedagógicos que permitan relacionar las diversas
            materias estudiadas en clase con la expedición; y, por otro, transmitir la importancia de saber compartir,
            ser solidario y superarse a sí mismo en una aventura humana.</p>
        <p>En el marco de este intercambio escolar, las clases que así lo desean pueden participar en un concurso
            presentando los trabajos realizados durante el año escolar. Los ganadores tienen la oportunidad de
            profundizar sus conocimientos teóricos en una salida espeleológica, acompañados de uno o varios miembros de
            la expedición.</p>
        <p>Este año han sido 38 las clases que, desde primaria hasta secundaria, pasando por centros tecnológicos y
            profesionales, han presentado una amplia gama de trabajos, todos ellos de una gran originalidad.</p></div>
</div>
