<h1>Projet scolaire&nbsp;2019&nbsp;: le bilan&nbsp;! </h1>
<div class="row">
    <div class="col-md-12"><p>Depuis 2008, Centre-Terre a noué un partenariat étroit avec l’Education Nationale pour
            permettre à des élèves toujours plus nombreux de suivre les expéditions et vivre les aventures de
            l’association depuis leur école. L’objectif est double&nbsp;: d’une part, organiser des projets
            pédagogiques en corrélation entre différentes matières étudiées en classe et des thématiques de
            l’expédition, et d’autre part transmettre des valeurs de partage, d’entraide et de dépassement de soi
            dans une aventure humaine.</p>
        <p>Dans le cadre de cet échange scolaire, les classes qui le souhaitent peuvent participer à un concours
            dont la finalité est de présenter les projets réalisés pendant l’année scolaire. Les lauréats ont
            l’opportunité d’approfondir leurs connaissances théoriques grâce à une sortie en milieu souterrain avec
            un ou plusieurs membres de l’expédition&nbsp;!</p>
        <p>Cette année ce sont 38 établissements, du cours préparatoire à la terminale, en passant par les
            enseignements adaptés et professionnels qui ont déposé des productions variées, toutes plus originales
            les unes que les autres.</p></div>
</div>
