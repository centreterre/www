    <div class="col-md-6"><p>Le projet scolaire prend de l’ampleur d’année en année et c’est une vraie satisfaction
            pour Centre-Terre qui, depuis 2010, a mis en place un forum dédié aux établissements, publié des fiches
            pédagogiques sur leur site internet et réalisé des visioconférences pour échanger avec les élèves
            pendant leurs expéditions. Plusieurs explorateurs prennent également de leur temps, avant ou après
            l’expédition, pour rencontrer des classes, partager leur expérience et répondre aux questions des
            enfants portant aussi bien sur la vie quotidienne que sur les découvertes scientifiques.</p></div>
</div>
<div class="row">
    <div class="col-md-12"><p>L’investissement paie des deux côtés, et les explorateurs comme les élèves
            s’enrichissent de cet échange.</p>
        <p>Le jeudi 23 mai 2019, au rectorat de Toulouse, le jury s’est réuni pour désigner les lauréats et prévoir
            les sorties spéléo avec les classes. Le jury était composé de&nbsp;:</p>
        <p>- Bernard TOURTE, chef de l’expédition</p>
        <p>- Elodie MULOT, responsable du projet scolaire au sein de Centre Terre</p>
        <p>- Damien CHIGOT, CTN auprès de la Fédération française de spéléologie</p>
        <p>- Valérie BOUKBEKER, chargée des actions culturelles au sein du rectorat de Toulouse</p>
        <p>Après quelques heures de débats, tous se sont mis d’accord sur les 4 productions à primer.</p></div>
