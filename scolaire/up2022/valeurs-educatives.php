<h1>Les valeurs éducatives de la Spéléologie</h1>
<p>Pratiquer la spéléologie nécessite de déployer des compétences, des savoir-faire et des attitudes qui développent des
    valeurs fortes : solidarité, partage, respect, engagement, connaissance de soi. La spéléologie, qui repose sur
    l’exploration du milieu souterrain et de son environnement extérieur présentent de nombreux atouts éducatifs qui
    contribuent auprès des jeunes à l’acquisition de connaissances et de compétences à tous les niveaux de scolarité et
    dans de nombreux champs disciplinaires. Centre Terre, par l’intermédiaire de ses explorations en milieux extrêmes,
    fait la promotion de toutes ces valeurs auprès des jeunes en développant des projets scolaires à chaque
    expédition.</p>
<p>Apprendre autrement devient une source de motivation pour tous les élèves et permet à la fois de récupérer des élèves
    décrocheurs voire même en rupture, mais aussi d’accompagner l’élève vers l’excellence. Le milieu souterrain est
    constitué de grottes et de gouffres creusés par l’eau. Ils constituent un patrimoine naturel et culturel témoin de
    l’histoire des évolutions de la Terre et des hommes. Se trouver confronté à cet héritage, à ses dimensions concrètes
    mais aussi symboliques et à la complexité de son évolution constitue une expérience éducative riche. « Explorer,
    Étudier, Partager » est la devise de Centre Terre.</p>
<h1>Le patrimoine karstique comme support pédagogique</h1>
<p>En France, on dénombre actuellement plusieurs milliers de km de galeries souterraines explorées par les spéléologues
    mais trop souvent méconnues par le grand public. Centre Terre, en communiquant sur ses expéditions à
    l’international, a pour objectif d’attirer l’attention des jeunes sur la richesse du karst et l’importance de sa
    préservation. La spéléologie en milieu scolaire peut devenir une activité de territoire qui permet aux jeunes de
    découvrir leur milieu de vie sous un angle particulier. La spéléologie est une discipline très riche qui s’articule
    autour de composantes éducatives bien identifiées dans le domaine de l’EPS : apprentissages moteurs, goût de
    l’effort, respect des règles de sécurité, solidarité, concentration, lecture du milieu et d’un itinéraire... Mais
    son exploitation dans les autres enseignements est pertinente au regard des différents domaines pouvant être abordés
    :</p>
<ul>
    <li>La ressource en eau : quantité-qualité-Éducation au Développement durable</li>
    <li>L’hydrologie souterraine : géologie</li>
    <li>La formation des grottes et des gouffres : géologie régionale</li>
    <li>La faune cavernicole et ses adaptations : biologie</li>
    <li>La protection du milieu environnant : Interactions entre surface et profondeur</li>
    <li>Les remplissages souterrains : Paléo-environnement et paléoclimat</li>
    <li>La préhistoire : histoire et géographie</li>
    <li>L’utilisation des cavernes depuis la préhistoire à nos jours : patrimoine et exploitation de ressources.</li>
    <li>L’art pariétal : histoire des arts</li>
    <li>La photographie et la vidéo souterraines : Arts plastiques</li>
    <li>La topographie souterraine : Mathématiques, Informatique, Technologie</li>
    <li>La cartographie : Géographie</li>
    <li>La littérature sur le milieu souterrain : de Jules Verne aux contes fantastiques</li>
    <li>Utilisation d’appareils de mesure et d’instruments : technologie</li>
</ul>
<p>Ainsi la spéléologie peut servir de support éducatif à une multitudes de disciplines en offrant des exemples concrets
    et un lieu d’étude privilégié.</p>
<p>Par l’observation du réel, les sciences et la technologie suscitent les questionnements des élèves et la recherche de
    réponses.</p>
<p>Par le recours à la démarche d’investigation, ces disciplines apprennent aux élèves à observer et à décrire, à
    déterminer les étapes d’une investigation, à établir des relations de cause à effet et à utiliser différentes
    ressources. Les élèves apprennent à utiliser leurs connaissances et savoir-faire scientifiques et technologiques
    pour concevoir et pour produire. Ils apprennent également à adopter un comportement éthique et responsable et à
    utiliser leurs connaissances pour expliquer des impacts de l’activité́ humaine sur la santé et l’environnement.</p>
<p>La spéléologie ainsi didactisée peut contribuer à faire acquérir la capacité́ à coopérer en développant le travail
    en groupe et le travail collaboratif à l’aide des outils numériques, ainsi que la capacité́ à réaliser des projets
    stimulants pour les élèves.</p>
<p>Pour illustrer ces plus-values éducatives liée à la spéléologie, il suffit de faire un focus sur tous les projets
    réalisés ces dernières années par les classes qui ont suivi les différentes expéditions. L’espace scolaire du site
    de Centre Terre permet d’expliquer comment il est possible d’intégrer la spéléologie dans les enseignements
    disciplinaires mais aussi alimenter de nombreux projets pédagogiques interdisciplinaires. La pédagogie du détour ne
    peut que susciter l’appétence des élèves d’autant plus que la spéléologie les amènera sur le terrain pour découvrir
    leur territoire. La mise en œuvre de tels projets suppose un travail collaboratif avec les spéléologues de Centre
    Terre mais aussi tous ceux de la Fédération Française de Spéléologie.</p>
<h1>Explorer - Étudier - Partager</h1>
<p>Les publications de Centre Terre : livres, films, documentaires et les activités de la Fédération Française de
    Spéléologie tout comme les supports pédagogiques académiques déjà mis à disposition par les enseignants de
    l’Education Nationale contribuent à la découverte des milieux karstiques. Des projets interdisciplinaires sont
    réalisés chaque année. Ces actions permettent l’acquisition de connaissances scientifiques, le développement de
    compétences et d’habilités motrices pour se déplacer dans ce milieu spécifique, dans un contexte où la solidarité
    est une composante forte de l’aventure souterraine. Les valeurs citoyennes sont le piédestal de la spéléologie.</p>
<p>Les retours d’expérience et les suivis des parcours de vie de ces jeunes, montrent que les valeurs éducatives de la
    spéléologie ont une influence positive et structurante dans leur construction personnelle mais aussi dans
    l’insertion professionnelle.</p>
<p>De même la nécessité́ de faire comprendre aux élèves l’impératif d’un développement durable et équitable des
    activités humaines est plus que jamais un enjeu incontournable.</p>
<p>Les activités de plein air et la spéléologie au premier rang permettent de comprendre les impacts engendrés par le
    rythme et de la diversité des actions de l’être humain sur la nature.</p>
<p>L’appropriation de la culture scientifique par une pratique structurée de la spéléologie permet aux jeunes de se
    distancier d’une vision anthropocentrée du monde et de leurs croyances pour entrer dans une relation scientifique
    avec les phénomènes naturels, le monde vivant et les techniques.</p>
<p>Cette posture est faite de curiosité, d’ouverture d’esprit et de capacité à observer, expérimenter, et raisonner.</p>
<p>Il n’en demeure pas moins que c’est aussi le lieu d’apprentissage des sensations et du ressenti, de l’expression des
    émotions et de la possibilité de découvrir sa personnalité et développer sa créativité.</p>
<p>C’est pour cette raison que Centre Terre mène toujours des projets scolaires à chacune de ses expéditions.</p>