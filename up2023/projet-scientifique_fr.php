<h2>3. Sciences de l'Homme : archéologie et pression anthropique</h2>
<p>
    Les différentes expéditions spéléo-karstologiques de Centre-Terre ont permis de mettre en
    évidence une ancienne occupation de Madre Dios en différents lieux, et cela depuis plus de 4500 ans
    (sépulture de la cueva Ayayema). L’historique de cette occupation est important car il permet de retracer
    la place des nomades de la mer (l’éthnie Kaweskar) qui peuplaient l’archipel jusqu’au milieu du XX ème
    siècle. Vivant de chasse et de cueillette, ce peuple nomadisait dans les archipels de Patagonie et a laissé
    des traces sous forme d’amas coquilliers, de grottes ornées, de sépultures et d’abris de passages situés
    parfois à l’intérieur de l’île. A chaque fois, nous avons découvert des témoins de cette occupation humaine,
    d’où la nécessité de poursuivre la découverte de nouveaux sites. Les travaux envisagés sont donc la
    poursuite des prospections côtières, le repérage de cavités, la cartographie détaillée des sites découverts
    et la documentation photographique... Aucune fouille archéologique ne sera entreprise et aucun objet à
    valeur archéologique ne sera prélevé sans autorisation des autorités chiliennes.
</p>
<p>
    Sur une échelle de temps plus récente, il est important de regarder l’impact global de l’Homme
    avec par exemple le repérage et l’inventaire de la dérive des pollutions actuelles : objets flottants à la
    surface de l’océan, débris sur les rivages ou même sur les glaciers, microparticules de plastiques...
</p>
