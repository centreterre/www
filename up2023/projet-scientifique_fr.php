<h2>Introduction</h2>
<p>
    Depuis plus de 25 ans, l’Association Centre-terre explore les îles calcaires des archipels de la
    province Ultima Esperanza à la région de Magallanes, en Patagonie chilienne (Diego de Almagro et Madre
    de Dios). Par 50° de latitude sud, ce territoire de l’extrême, battu par les vents et les pluies d’un climat
    subpolaire hyper-humide, est l’objet d’une nouvelle expédition géographique et spéléologique. Etudier
    cet espace en milieu extrême, vierge de toute présence humaine, représente une opportunité unique à la
    fois dans le contexte des changements climatiques actuels, mais aussi de la crise socio-environnementale
    globale du 21 ième siècle.
</p>
<p>
    Le projet scientifique UP2022 a pour but d’accroître notre connaissance de cet espace unique —
    les « glaciers de marbre » — à partir d’une équipe transdisciplinaire mêlant prospection, exploration,
    recherches de terrain et de laboratoire. A cela s’ajoute une étude de reconnaissance sur les grands glaciers
    du Hielo Patagonico Sur et notamment sur les cavités intra- et sous-glaciaires indicateurs de la fonte
    glaciaire accélérée. Ce projet est articulé autour de trois thématiques : les sciences de la Terre, les sciences
    du Vivant et les sciences de l'Homme. Il est décliné en fiches thématiques portées par des scientifiques
    présents sur le terrain et poursuivant des analyses en laboratoire en collaboration avec d’autres
    chercheurs. Ce défi est d’autant plus grand que toute l’équipe est consciente que les archipels inhabités
    de Patagonie restent cependant connectés à l’ensemble de la planète, en particulier au niveau climatique
    et océanique. La protection Unesco de ce patrimoine unique est donc une étape indispensable qui doit
    permettre aussi de montrer, en particulier à travers un film, que l’avenir de la planète passe
    obligatoirement par un meilleur équilibre Homme-Nature, sans quoi ces recherches resteront vaines.
</p>
