<h2>2. Sciences du Vivant, biologie, écologie et biodiversité</h2>
<p>
    La biologie de Madre de Dios permet d’étudier la diversité et l’adaptation de la faune et de la flore
    dans un milieu aux conditions climatiques extrêmes ayant connu l’impact direct des glaciations au cours
    du Quaternaire. Après la dernière glaciation, les écosystèmes ont partiellement subi une « remise à zéro
    » et la recolonisation de ces habitats n’a pu se faire qu’à l'issue de celle-ci. La biocénose actuelle est donc
    directement liée à cet héritage ainsi que par un habitat morcelé, des conditions climatiques rudes et un
    impact anthropique quasi inexistant, celui des indiens Kaweskars ayant été très faible. Son étude est donc
    d'un intérêt primordial pour mieux comprendre la capacité des espèces à coloniser plus ou moins
    rapidement des systèmes insulaires vierges, même si les effets des changements globaux ne peuvent être
    ignorés. Dans ce contexte, plusieurs travaux sont envisagés :
</p>
<ul>
    <li>Relevés botaniques avec constitution d’un herbier, relevés mycologiques et étude des algues marines ;</li>
    <li>Etude de la biodiversité (mollusques, chiroptères, oiseaux, insectes) et leur adaptation à cet espace
        singulier comme les habitats en falaises (albatros) ;
    </li>
    <li>Collecte et études de la faune souterraine (siphons, rivières souterraines) ;</li>
    <li>Etude de la biodiversité microbienne dans les grottes, dans les tourbières (sphaignes...).</li>
</ul>
