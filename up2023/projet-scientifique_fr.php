<h2>1. Sciences de la Terre : glaciologie, géologie, géomorphologie et paléoclimatologie</h2>
<p>
    Les îles calcaires de Patagonie appartiennent au prisme d’accrétion de la cordillère des Andes. Ces
    roches volcano-sédimentaires et métamorphiques sont l’ancienne marge pacifique du paléocontinent
    Gondwana. Les mouvements tectoniques lors du mésozoïque, puis l’érosion les a mis au jour au contact
    du batholite patagon (granites). Lors du dernier maximum glaciaire (il y a environ 22.000 ans), le secteur
    était largement recouvert par la calotte glaciaire. L’agencement des roches est d’une géométrie très
    complexe, multipliant les contacts entre calcaires perméables et roches imperméables (grès),
    conditionnant ainsi les pertes et les écoulements souterrains karstiques. Le retrait glaciaire a libéré de
    profonds fjords (les seno de Patagonie), et depuis une très forte érosion de ces calcaires se poursuit, à la
    fois sous forme de dissolution superficielle, et par karstification en profondeur.
    Les travaux envisagés s’intéressent à des échelles de temps diverses :
</p>
<ul>
    <li>
        Tout d’abord la reprise de la carte géologique de Madre de Dios avec des observations et
        mesures sur le terrain.
    </li>
    <li>
        Préciser l’extension des systèmes karstiques (pertes, résurgences) et explorer-topographier
        des nouvelles cavités susceptibles de contenir des dépôts karstiques (varves, stalagmites) qui
        ont enregistré l’évolution de l’environnement.
    </li>
    <li>
        Poursuivre l’étude des remplissages d’origine glaciaire et tardiglaciaire reconnus dans
        plusieurs cavités majeures de Madre de Dios (Réseaux du Jackpot, de Punta Blanca) pour
        préciser l’histoire l’évolution du karst et du climat.
    </li>
    <li>
        Continuer les reconstructions paléoclimatiques à partir de l’étude des stalagmites, avec pour
        but d’étendre les enregistrements existants au-delà de la dernière période glaciaire. Ce travail
        sera complété par le prélèvement et l’étude de carottes de tourbe pour les parties les plus
        récentes des enregistrements.
    </li>
    <li>
        Etude et topographie des formes pseudo-karstiques (pertes, cavités dans la glace) et
        production de modèles surfaciques 3D sur le glacier afin d’observer la dynamique de fluage.
    </li>
</ul>
