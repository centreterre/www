        <h1>¡Colabora con la expedición Última Patagonia 2023!</h1>
        <p>En enero de 2023, Centre Terre organiza una nueva expedición espeleológica y geográfica de dos meses a las islas de la Patagonia chilena.
            Los objetivos de este nuevo proyecto son la exploración de los molinos glaciares de la zona del seno Peel y la exploración de cavidades
            calcáreas en la parte norte de Madre de Dios (sector estero Egg). La expedición de 2023 va acompañada de un componente científico más
            amplio que nunca, con temas que abarcan la glaciología (estudio de la dinámica del glaciar explorado), el paleoclima, la geología, la
            fauna (mamíferos), la flora (inventario botánico), la biología (biodiversidad microbiana) y las ciencias humanas. Al mismo tiempo, se
            llevará a cabo un proyecto escolar en colaboración con el Ministerio de Educación francés durante el curso 2022-2023 y la comunidad
            educativa de Puerto Edén, la localidad más cercana al archipiélago Madre de Dios. En Francia, varias decenas de clases se han inscrito y
            ya se están beneficiando del apoyo educativo. Por último, durante esta aventura se producirá una nueva película de 90 minutos que será
            emitida por ARTE en otoño de 2023.
        </p>
