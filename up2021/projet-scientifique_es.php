<h2>1. Ciencias de la Tierra: glaciología, geología, geomorfología y paleoclimatología</h2>
<p>
    Las islas calcáreas de Patagonia pertenecen al prisma de acreción de la cordillera de los Andes.
    Esta rocas vulcano-sedimentarias y metamórficas son el antiguo margen pacífico del paleocontinente
    Gondwana. Los movimientos tectónicos durante el mesozoico, seguidos de la erosión, las ha sacado a la
    superficie en el contacto con el batolito patagónico (granito). Durante el último máximo glaciar (hace unos
    22.000 años), el sector estaba ampliamente cubierto por el casquete glaciar. La distribución de las rocas
    es de una geometría muy compleja, multiplicando los contactos entre calizas permeables y rocas
    impermeables (arenisca), condicionando así los sumideros y filtraciones subterráneas kársticas. La retirada
    de los glaciares ha liberado profundos fiordos (los senos patagónicos), a la que le ha seguido una enorme
    erosión de estas calizas, a la vez en forma de disolución superficial y por karstificación en profundidad.
    Los trabajos previstos se enfocan en escalas temporales distintas:
</p>
<ul>
    <li>Empezando por retomar el mapa geológico de Madre de Dios con observaciones y mediciones
        en terreno.
    </li>
    <li>Precisar la extensión de los sistemas kársticos (sumideros, resurgencias) y explorar y
        topografiar nuevas cavidades susceptibles de contener depósitos kársticos (varvas,
        estalagmitas) que han registrado la evolución del medioambiente.
    </li>
    <li>Continuar el estudio de los rellenos de origen glaciar y tardiglaciar identificados en numerosas
        cavidades de dimensiones de Madre de Dios (sistema Jackpot, Punta Blanca) para precisar la
        historia de la evolución del karst y del clima.
    </li>
    <li>Continuar reconstruyendo los paleoclimas a partir del estudio de las estalagmitas, con el
        objetivo de ampliar los registros existentes más allá del último periodo glaciar. Este trabajo se
        complementará con toma de muestras y estudio de testigos de turba para las partes más
        recientes de estos registros.
    </li>
    <li>Estudio y topografía de las formas pseudo-kársticas (sumideros, cavidades glaciares) y
        producción de modelos superficiales 3D en el hielo para observar la dinámica de fluencia.
    </li>
</ul>
