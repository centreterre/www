<h2>3. Ciencias del Hombre: arqueología y presión antrópica</h2>
<p>
    Las diferentes expediciones espéleo-karstológicas de Centre Terre han permitido sacar a la luz una
    antigua ocupación de Madre de Dios en distintos puntos y, ello, desde hace 4500 años (sepultura de la
    cueva Ayayema). El pasado de esta ocupación es importante porque permite seguir los pasos de los
    nómades del mar (etnia kawésqar) que pobló el archipiélago hasta mediados del siglo XX. Viviendo de la
    caza y de la colecta, este pueblo habitó, como nómadas, los canales patagónicos y dejó huella en forma de
    conchales, cuevas rupestres, sepulturas y abrigos temporales situados, en ocasiones, en el interior de la
    isla. Siempre hemos descubierto rastros de esta ocupación humana, de ahí la necesidad de seguir
    localizando nuevos sitios. Los trabajos previstos se basan, pues, en la prospección costera, localización de
    cavidades, cartografía detallada de sitios descubiertos y la documentación fotográfica. No se realizarán
    excavaciones arqueológicas ni se extraerá ningún objeto arqueológico sin autorización de las autoridades
    chilenas.
</p>
<p>
    En una escala temporal más reciente, es importante observar el impacto global del hombre como,
    por ejemplo, localizando e inventariando la deriva de los contaminantes actuales: objetos flotantes en la
    superficie del océano, desechos en las costas o incluso en los glaciares, micropartículas de plásticos...
</p>
