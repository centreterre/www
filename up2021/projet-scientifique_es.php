<h2>2. Ciencias Naturales: biología, ecología y biodiversidad</h2>
<p>
    La biología de Madre de Dios permite estudiar la diversidad y la adaptación de la fauna y de la flora
    de un medio con condiciones climáticas extremas que ha conocido el impacto directo de las glaciaciones
    durante el Cuaternario. Tras la última glaciación, los ecosistemas, en particular, sufrieron una «reseteo a
    cero» y la recolonización de estos hábitats no pudo darse hasta superada esta fase. La biocenosis actual
    está, pues, directamente relacionada a esta herencia y a un hábitat fragmentado, a condiciones climáticas
    duras y a un impacto antrópico casi inexistente, siendo el de los Kawésqar muy leve. Por ello, su estudio
    reviste un interés especial para lograr comprender la capacidad de las especies para colonizar, más o
    menos rápidamente, unos sistemas insulares vírgenes, sin ignorar los efectos de los cambios globales. En
    este contexto, se prevé realizar varios trabajos:
</p>
<ul>
    <li>Muestreo botánico para conformar un herbario, muestreo micológico y estudio de algas marinas.- Estudio de la
        biodiversidad (moluscos, quirópteros, aves, insectos) y su adaptación a este singular
        espacio, como los hábitats en acantilados (albatros).
    </li>
    <li>Colecta y estudio de fauna subterránea (en sifones y ríos subterráneos).</li>
    <li>Estudio de la biodiversidad microbiana en las cuevas, en las turberas (sphagnum).</li>
</ul>
