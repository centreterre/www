<h3>Introducción</h3>
<p>Desde hace más de 25 años la asociación Centre Terre explora las islas de caliza Diego de Almagro
    y Madre de Dios, situadas en los canales patagónicos de la provincia Última Esperanza, en la Región de
    Magallanes y la Antártica chilena. Ubicado en la latitud 50° Sur, este territorio austral, azotado por los
    vientos y las lluvias de un clima subpolar hiper-húmedo, será objeto de una nueva expedición geográfica
    y espeleológica. Estudiar este territorio en un medio extremo, exento de vida humana, representa una
    oportunidad única tanto en el contexto de los cambios climáticos, como de la crisis socio-medioambiental
    global de siglo XXI.
</p>
<p>
    El proyecto científico UP2022 tiene como objetivo ahondar nuestro conocimiento de este espacio
    único, los glaciares de mármol, a partir de un equipo pluridisciplinario que aúna prospección, exploración,
    trabajo de campo y de laboratorio. A ello se suma el trabajo de reconocimiento de las grandes lenguas
    glaciares del Hielo Patagónico Sur y, principalmente, de las cavidades intra y subglaciales, indicadores del
    deshielo acelerado. Este proyecto se articula en torno a tres ejes: las Ciencias de la Tierra, las Ciencias
    Naturales y las Ciencias del Hombre. Se declina en fichas temáticas realizadas por científicos que estarán
    en terreno y que se complementará con análisis en laboratorio en colaboración con otros investigadores.
    Este es un inmenso reto. Todo el equipo es consciente de que los archipiélagos de Patagonia, por muy
    deshabitados que estén, están conectados al resto del planeta, en particular, a nivel climático y oceánico.
    La protección UNESCO de este patrimonio único es, pues, una etapa indispensable que también permitirá
    mostrar, sobre todo a través de una película, que el futuro del planeta pasa, necesariamente, por un mejor
    equilibrio hombre-naturaleza, sin el que estas investigaciones serán en vano.
</p>
