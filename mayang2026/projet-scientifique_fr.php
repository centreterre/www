<h1 style="text-align: center;">Objectif Mayang, Projet Scientifique</h1>
<hr>
<div style="text-align: center;font-weight: bold">
    Une expédition Centre Terre en Papouasie Nouvelle-Guinée<br>
    10 janvier - 19 mars 2026
</div>
<hr>
<p> Après le succès des nombreuses expéditions en Patagonie Chilienne, Centre Terre s’engage à nouveau dans une grande
    aventure, cette fois-ci de l’autre côté du Pacifique. Elle aura pour cadre l’île de Nouvelle-Bretagne, en
    Papouasie-Nouvelle-Guinée, île devenue mythique dans le milieu spéléologique pour l’engagement qu’elle requiert et
    surtout par l’énorme dimension de ses réseaux karstiques. C’est en effet sur les montagnes Nakanaï – où nous nous
    rendrons – qu’a été exploré par les précédentes expéditions françaises le réseau de Muruk, premier moins mille
    mètres de profondeur et, encore à ce jour, le plus profond de l’hémisphère sud.</p>
<p> Notre expédition se propose de partir à la recherche du méga-collecteur supposé de Mayang, dont le débit estimé de
    20 à 30 m³/s à l’étiage en fait l’une des plus grosses émergences karstiques au monde. Malgré les assauts de
    plusieurs expéditions spéléologiques d’envergure, son trajet souterrain demeure inconnu.</p>
<p> Nous prospecterons son bassin d’alimentation supposé, une vaste zone encore vierge de toute exploration
    spéléologique. Si un secteur avec un tel potentiel demeure à ce jour encore inexploré, c’est bien aux difficultés
    d’accès qu’il le doit.</p>
<p> La force de Centre Terre est de pouvoir mettre en œuvre une importante logistique et une forte équipe
    pluridisciplinaire pour explorer les coins les plus reculés de la planète et se frotter à des phénomènes uniques au
    monde. Comme à chaque fois, la science aura une place prépondérante dans nos objectifs, y compris la spéléologie –
    un sport au service de la science, selon Norbert Casteret – car tout ou presque demeure inconnu et bien peu de
    scientifiques ont pu accéder au cœur de la dense forêt des Monts Nakanaï.</p>
<p> Les scientifiques de Centre Terre, présents sur place ou participant aux préparatifs et traitements post-expédition
    depuis leurs labos en France, ont déjà défini plusieurs axes de recherches, déclinés ici selon les domaines
    scientifiques. La composition de l’équipe n’étant pas encore totalement figée, ces axes pourront être amenés à
    évoluer.</p>
<p> Les enjeux de telles études sont multiples et importants : outre le fait de ramener des données utiles à la science
    concernant une région peu étudiée du fait de son inaccessibilité, il se trouve que cette région fait partie des
    hotspots de biodiversité et que les montagnes Nakanaï, suite aux résultats révélés par les précédentes expéditions
    d’explorations spéléologiques et scientifiques, ont été identifiés par l’État papou comme élément du bien naturel
    sériel inscrit depuis 2006 sur la liste indicative nationale du Patrimoine mondial sous l’appellation des « Sublimes
    karsts de Papouasie-Nouvelle-Guinée ». Les résultats scientifiques de l’expédition Mayang 2026 pourraient ainsi
    apporter une contribution majeure et décisive à une candidature au Patrimoine mondial de l‘UNESCO.
</p>
