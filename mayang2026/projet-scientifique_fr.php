<b>Sciences de la Terre : la spéléologie pour révéler toutes les valeurs géologiques du karst des Nakanaï.</b>
<p>Des calcaires purs et peu compacts formés il y a 15 millions d’années (calcaires miocènes dits de Yalam), une
    pluviométrie parmi les plus fortes de la planète, un couvert végétal dense et une forte sismicité : les Monts
    Nakanaï cumulent tous les superlatifs et tous les ingrédients pour une karstification hors normes, donnant des
    paysages de surface très chaotiques (« karst polygonal ») et des cavernes géantes à méga-rivières souterraines.</p>
<h3>2 - Au pays des méga-résurgences en climat hyper humide : quantifier les écoulements des eaux dans le karst.</h3>
<b>Membres Centre Terre ressource : Fabien Hobléa, Laurent Morel et Christophe Rognon.</b>
<p>Le but principal de notre expédition est d’atteindre le collecteur de la méga-résurgence de Mayang, l’une des plus
    importantes au monde : son débit a été estimé à 20 m³/s à l’étiage, et à probablement plus de 100 m³/s lors des
    crues. L’un des facteurs permettant ce phénomène est bien sûr l’abondance des précipitations. Des données
    météorologiques existent mais concernent le littoral, et l’abondance des précipitations augmente très fortement au
    fur et à mesure que l’on s’élève dans les massifs. Lors de l’expédition « Nakanaï 98 », Philippe Audra avait ainsi
    mesuré la pluviométrie à Muruk sur un mois et estimé la valeur des précipitations annuelles à près de 12 500 mm
    (Audra, 2001).</p>
<p>Notre présence sur le massif pendant près de deux mois nous permettra d’affiner ces résultats en mettant en place une
    station météorologique de terrain (pluviométrie, température, pression barométrique et hygrométrie). Nous pourrons
    laisser en place une partie de l’appareillage jusqu’à la prochaine expédition, comme nous l’avons déjà fait avec
    succès sur l’île de Madre de Dios, en Patagonie chilienne, et acquérir ainsi des données sur l’ensemble de
    l’année.</p>
<p>Ayant choisi de nous intéresser à une zone vierge de toute prospection spéléologique au sein du bassin d’alimentation
    supposé de Mayang, nous n’avons à ce jour aucune certitude sur le type de cavités rencontrées et leurs débits. Dans
    tous les cas, nous procéderons à des mesures de débits par jaugeage, et à des analyses physico-chimiques des eaux.
    Ces données seront corrélées avec celles des précipitations. Selon les débits rencontrés, nous pourrions envisager
    de mettre en place des traçages.</p>
<p>Quant à la résurgence de Mayang, qui n’a été observée pour la première fois par des spéléologues qu’en 1985, elle est
    impénétrable, sortant d’un immense chaos de blocs. Selon nos possibilités sur le terrain, et en fonction des
    traçages éventuellement mis en place, nous tenterons de l’atteindre afin de pouvoir en estimer plus précisément le
    débit, ce qui représente un véritable défi métrologique.</p>
<h3>3 – Karstification et activité sismique : le rôle des séismes dans la formation des grands volumes</h3>
<b>Membres Centre Terre ressource : Fabien Hobléa et Christophe Rognon.</b>
<p>La formation des grands réseaux spéléologique de Nouvelle-Bretagne résulte principalement de la combinaison entre
    d’une part la pureté en carbonate de calcium des calcaires miocènes de Yalam, qui les rend très solubles et réactifs
    à l’érosion chimique par les forts écoulements d’eau, et d’autre part leur nature plutôt tendre et peu compacte, due
    à leur relative « jeunesse », les rendant aussi sensibles à l’érosion mécanique et gravitaire (éboulements
    internes). Cette instabilité intrinsèque peut être exploitée par la forte sismicité de la région, qui est soupçonnée
    de jouer un grand rôle dans la formation des grands volumes au vu des observations et expériences vécues par les
    expéditions précédentes. Pour pouvoir quantifier le rôle de la sismicité dans la formation des grands réseaux
    souterrains du massif, des observations in situ seront réalisées pour retrouver les traces et indices de
    paléo-séismes et leurs liens avec la formation des conduits. Des prélèvements d’éventuels spéléothèmes (concrétions)
    affectés par ces paléo-secousses pourront être effectués pour datation de l’événement sismique identifié.</p>
<h3>4 – Géomorphologie</h3>
<b>Membres Centre Terre ressource : Fabien Hobléa, Charlotte Honiat et Christophe Rognon.</b>
<p>Malgré la présence de la forêt dense, la géomorphologie karstique très chaotique des Monts Nakanaï est tout à fait
    perceptible et observable in situ comme sur images aériennes et satellitaires, tant elle est hypertrophiée (karst
    polygonal, canyons étroits et très profonds, aux parois très verticales). Une cartographie des formes et modelés du
    relief reste à effectuer et la zone prospectée en surface lors de l’expédition pourra apporter de nouveaux éléments
    au puzzle des données géomorphologiques déjà collectées par les précédentes expéditions sur des secteurs voisins un
    peu plus bas en altitude. Pourra-t-on observer les traces et signes d’un étagement morpho-climatique des modelés
    karstiques en fonction de l’altitude comme cela apparaît de façon plus spectaculaire sur le karst de haute-montagne
    de la péninsule de Huon sur l’île de Nouvelle-Guinée ?</p>
<p>Les cavernes sont également des formes du relief terrestre sources d’informations sur la genèse et l’évolution
    paléogéographique régionale. Elles constituent aussi des fenêtres ouvertes dans les entrailles des couches
    calcaires, susceptibles de révéler des fossiles exhumés par la dissolution du calcaire, comme, cet os long de
    baleine découvert en 1995 encore pris dans la paroi d’une galerie du gouffre de Muruk.</p>
<h3>5 – Paléoclimat</h3>
<b>Membre Centre Terre ressource : Charlotte Honiat.</b>
<p>Les concrétionnements abondants dans les cavernes de ce karst forestier sont également de précieux enregistreurs et
    archives des climats et des environnements du passé et de leur évolution à l’échelle des millénaires voire de
    quelques millions d’années. Les études sur les concrétions des régions équatoriales sont en plein essor, permettant
    notamment de mieux connaître l’évolution des régimes de précipitations en rapport avec les phénomènes saisonniers
    des moussons et avec les cycles pluriannuels de type El Nino. Des études récentes sur l’île de Bornéo ont démontré
    que les reconstructions de paléotempérature à partir des spéléothèmes sur le très long-terme sont fiable et peuvent
    refléter les variations de température de l'hémisphère sud ainsi que les concentrations atmosphériques de CO2
    (Loland et al. 2022). Il serait intéressant de comparer ces enregistrements à ceux de Papouasie Nouvelle Guinée.
    Cependant, avant d’envisager une campagne de prélèvements il faut s’assurer que les conditions micro climatiques de
    la grotte où ces échantillons seront prélevés soient stables. Dans un esprit de conservation, on peut d’abord
    envisager de mettre en place un suivi des conditions dans quelques cavités à l’aide de capteur-enregistreur de
    température et de prévoir la collecte de l’eau d’égouttement dans la cavité ; complémentaire au suivi mis en place
    en surface à l’aide de la station météorologique. On pourra ainsi vérifier la qualité du transfert du signal
    climatique de l’eau de pluie, traversant un sol puis s’infiltrant dans la roche, jusqu’à la cavité et la formation
    d’une concrétion : un prérequis indispensable pour toute étude paléoclimatique.</p>
<h2>Sciences du vivant</h2>
<b>Contribuer à l’évaluation d’un hot-spot de la biodiversité mondiale</b>
<p>Les habitats tropicaux forestiers sont riches d’une biodiversité exceptionnelle dont l’importance écologique est
    mondiale. Elle est toutefois soumise à un ensemble de menaces d’ordre anthropique récemment identifiées et
    quantifiées (White et al. 2021). La gestion de ces menaces est une voie d’action nécessaire face aux enjeux globaux
    d’érosion de la biodiversité, notamment Néo Guinéenne, mais elle doit en premier lieu s’appuyer sur la connaissance
    du milieu et des espèces. Dans ces montagnes particulièrement isolées, l’inventaire des espèces floristiques et
    faunistiques est, encore aujourd’hui, un véritable challenge et reste largement incomplet. Notre expédition se
    déroulant dans un secteur vierge, elle contribue ainsi à combler ce manque.</p>
<h3>6 – Une faune souterraine très largement méconnue, des espèces endémiques remarquables : inventorier la faune
    souterraine terrestre et aquatique</h3>
<b>Membre Centre Terre ressource : Franck Bréhier</b>
<p>De par la grande difficulté d’accès des karsts de Papouasie Nouvelle-Guinée, leur faune souterraine est restée
    longtemps méconnue, les premières études datant de 1976 (Beron pour la Nouvelle-Irlande et Chapman pour les monts
    Hindenburg de Nouvelle-Guinée). En dépit de leur faible nombre, les collectes réalisées lors de précédentes
    expéditions spéléologiques ou scientifiques ont révélé des formes terrestres et aquatiques endémiques uniques,
    certaines présentant un degré de troglobiomorphie très élevé. C’est le cas par exemple du crabe Trogloplax joliveti,
    Guinot, 1986 collecté dans les monts Nakanaï lors de l’expédition de 1985 et pour lequel il a fallu créer une
    sous-famille, de l’Atyidae Jolivetya foresti, Cals 1986 ou encore, pour la faune terrestre de Trogloclivina brehieri
    Deuve, 2003. Dans ce contexte d’indigence de données et de grande richesse biologique, l’intérêt de mener des
    collectes de la faune souterraine est évident, et les découvertes devraient être au rendez-vous.</p>
<p>Moyens mis en œuvre :</p>
<p>Sur le terrain, seront échantillonnées et la faune terrestre, et la faune aquatique, y compris pour cette dernière en
    plongée souterraine. Seront privilégiées des techniques simples adaptées aux conditions de l’expédition : chasse à
    vue, poses de nasses appâtées, utilisation de filet à plancton tracté, pose de filets aux résurgences, etc. Pour la
    faune terrestre, un échantillonnage comparatif de la faune du sol sera réalisé, incluant des techniques de piégeage
    et de lavage des sols. Le tri sera fait sur place sous loupe binoculaire. Le matériel biologique sera conservé dans
    l'éthanol.</p>
<p>De retour en France, un tri plus approfondi et une série de photographies seront réalisés avant envoi des
    échantillons aux spécialistes de chaque groupe pour détermination et description, le cas échéant.</p>
<p>Liens envisagés : MNHN Paris, MNHN Stuttgart, Université de Pomio.</p>
<h3>7 – A l’écoute de l’avifaune</h3>
<b>Membre Centre Terre ressource : Marie Eveillard-Buchoux</b>
<p>L’avifaune est un indicateur significatif de la santé écologique d’un milieu. Elle constitue en outre une faune
    remarquable et fortement endémique des forêts tropicales et équatoriales. Son inventaire présente dès lors un grand
    intérêt. L’expédition contribue ainsi à mesurer la diversité avifaunistique des Monts Nakanaï et de la comparer avec
    les bases de données des secteurs tropicaux mieux connues.</p>
<p>La faune forestière étant globalement discrète et peu visible sous le dense couvert végétal, c’est par ses sons
    qu’elle est le plus manifeste. L’enregistrement des chants d’oiseaux est ainsi le moyen le plus efficace, et
    couramment utilisé, pour réaliser les inventaires avifaunistiques en forêt les plus complets possibles. C’est sur ce
    procédé que repose ce volet scientifique.</p>
<p>Moyens mis en œuvre :</p>
<p>Nous installerons un dispositif autour du ou des camps de base permettant un enregistrement sonore et/ou vidéo de
    l’environnement en continu durant toute la période de l’expédition. Les enregistrements sont complétés par des
    observations ponctuelles in situ et des prises de photographies. Les données seront traitées et analysées en
    laboratoire au retour d’expédition afin d’identifier les espèces présentes.</p>
<h2>Sciences humaines</h2>
<h3>8 – Archéologie : sur la trace des habitants des forêts</h3>
<b>Membre Centre Terre ressource : Didier Lamotte</b>
<p>Le peuplement de la Papouasie-Nouvelle-Guinée remonte à une période très ancienne. Des analyses génomiques réalisées
    sur les populations mélanésiennes ont montré que les premières migrations humaines vers la Papouasie-Nouvelle-Guinée
    ont eu lieu il y a environ 50 000 à 65 000 ans, lorsque les ancêtres des Papous et des Aborigènes australiens sont
    arrivés sur le supercontinent appelé Sahul, qui comprenait la Papouasie-Nouvelle-Guinée, l'Australie et la
    Tasmanie.</p>
<p>D’abord établie près des côtes, la population s'est ensuite dispersée vers les hauts plateaux et les vallées
    d'altitude colonisant ainsi lentement l’intérieur des terres. Dans l’île principale, plusieurs fouilles
    archéologiques ont révélé ces vestiges d’occupation. Ainsi, dans le sud de l'île, dans une vallée particulièrement
    isolée de la province des Hautes-Terres occidentales, le vaste site archéologique de Kuk est connu pour son
    agriculture indigène presque continue depuis 7000, voire 10 000 ans. Ce site est désormais classé par l’UNESCO. Un
    autre site, au sud-ouest, a quant à lui livré les vestiges les plus anciens de l’île, datés vers -49000 ans (site
    d’Ivane). Si de nombreux sites de plein air ont été largement documentés depuis les premières fouilles en 1959,
    quelques sites en grottes ou abris sous roche ont également été découverts et fouillés. On peut citer en exemple :
    l’abri sous roche de Yuku, province des Hautes-Terres occidentales, fouille de 1959, l’abri sous roche de Niobe,
    (Chimbu), fouille de 1960, la grotte d’Aibura, (Hautes-Terres orientales), fouille de 1964, etc. Plus récemment, ce
    sont les abris sous roche de Manim (Jiwaka), fouille de 2019 ou le complexe de grottes d’Eripe (Golfe), fouille de
    2024 qui ont été étudiés par les archéologues. Certains sites conservent des arts rupestres : pétroglyphes dans la
    grotte de Walufeni (Hautes-Terres méridionales), abris ornés de la région du Sépik, etc.</p>
<p>L’équipe de Mayang 2026 intègre un archéologue ayant plus de 25 ans d’expérience dans le domaine de l’archéologie
    préventive. En cas de découverte d’un site archéologique (grotte, abris sous roche, voire site de plein air), nous
    veillerons donc à préserver les traces d’éventuels prédécesseurs et à les protéger le cas échéant. Les vestiges
    visibles seront décrits et cartographiés, les sites topographiés. Une couverture photographique la plus détaillée
    possible pourra être réalisée à des fins de conservation (photographies de détails, photogrammétrie, etc.). Aucune
    fouille archéologique ne sera entreprise et aucun objet à valeur archéologique ou patrimoniale ne sera prélevé ou
    déplacé.</p>
<p>Les éventuelles découvertes seront portées à la connaissance des habitants du massif, héritiers des modes de vie et
    d’occupation des espaces d’altitude aujourd’hui délaissés, afin d’être confrontés à la mémoire et aux savoirs
    locaux. Les autorités du pays seront également averties au terme de l’expédition ou immédiatement si les découvertes
    le justifient.</p>
<h3>9 - Ethnographie et ethno-géographie : regard sur 50 ans de trajectoire du socio-écosystème de la forêt papoue des
    Nakanaï.</h3>
<b>Membre Centre Terre ressource : Fabien Hobléa</b>
<p>L’expédition Mayang 2026 s’inscrit dans la continuité d’expéditions françaises menées dans le secteur depuis 1978, ce
    qui nous permet d’avoir un recul de près de 50 ans sur l’évolution du socio-écosystème très particulier de la forêt
    papoue des Nakanaï, ethnotope autant que biotope, observatoire privilégié de l’évolution des relations des peuples
    premiers à leur environnement, et des effets de leur mise en contact avec « l’économie-monde », de la présence
    australienne à celle des compagnies forestières asiatiques, sans oublier les effets de la présence sporadique mais
    récurrente d’expéditions scientifiques impliquant et interagissant fortement avec les populations et structures
    sociales locales. Les rapports aux éléments naturels et notamment aux phénomènes naturels violents (cyclones,
    séismes, crues, éruptions volcaniques) constituent un thème d’investigation particulièrement intéressant. Il en est
    de même pour ce qui concerne le projet d’interroger les habitants et responsables locaux sur la question de la
    gestion des ressources naturelles du territoire, à commencer par la grande forêt, mais aussi l’eau des rivières,
    ressource vitale pour les villages côtiers installés aux embouchures.</p>
<h3>10 – Vers une reconnaissance et une protection de la valeur patrimoniale des monts Nakanaï.</h3>
<b>Membre Centre Terre ressource : Fabien Hobléa</b>
<p>L’expédition sera également attentive aux signes impactants des activités humaines sur les éléments de la « zone
    critique » constitutifs des paysages de la forêt primaire et des milieux karstiques des Nakanaï, de surface et
    souterrains, biotiques et abiotiques : faune-flore-fonge, sols, substrat, eaux de surface et souterraines… Il
    s’agira de consigner et rapporter ces signes d’une manière objective et scientifiquement exploitable, tout en
    veillant à limiter et éviter nos propres impacts in situ susceptibles de porter atteinte à l’intégrité du milieu.
    Soulignons cependant que l’empreinte d’une expédition d’une vingtaine de personnes réparties sur moins de 3 mois sur
    un vaste secteur sans station prolongée en un point unique, agissant de manière consciente et responsable selon une
    logistique adaptée, est sans commune mesure avec celle d’activités d’exploitation à grande échelle. Ainsi les partis
    pris d’une logistique fondée sur des camps de base et avancés en structures légères et éphémères, sur une approche
    et des déposes aéroportées au « compte-goutte » moins intrusives qu’une colonne de dizaines de spéléologues et «
    porteurs » taillant depuis la côte à travers la forêt, manifestent la volonté de la recherche du moindre impact
    chère à Centre Terre et aux scientifiques impliqués. Ce d’autant plus que nous évoluerons dans un milieu à haute
    valeur patrimoniale.</p>
<p>Les observations et données récoltées par l’expédition, établies en lien avec l’Université et l’antenne du WWF à
    Pomio, structurées selon les standards internationaux en vigueur en matière d’inventaires des patrimoines naturels
    (biopatrimoines, géopatrimoines), pourront ainsi servir tant à l’évaluation et à la reconnaissance des valeurs
    patrimoniales des Nakanaï qu’à l’établissement d’un plan de gestion conservatoire du massif dans la perspective
    d’une candidature des « Sublimes karsts de Papouasie-Nouvelle-Guinée » au Patrimoine mondial</p>
